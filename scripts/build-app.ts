// Compiles the desktop app (scripts/app.ts) into single executables, with the
// production web client and the icon embedded.
//
//   bun run build:app                                  # this computer's platform
//   bun run build:app --target=bun-windows-x64,bun-linux-x64
//   bun run build:app --target=all --package           # also package each one for release
//
// Output goes to dist/UniversalWisdomLibrary-<version>-<os>-<arch>/:
//   Windows  Universal Wisdom Library.exe (with its icon and no console window
//            when built on Windows; installer/windows.iss wraps it in a setup
//            program, see the release workflow)
//   macOS    Universal Wisdom Library.app, packaged as a .dmg on a Mac (a .zip
//            elsewhere)
//   Linux    Universal Wisdom Library, packaged as a .tar.gz
// Each comes with a short "READ ME FIRST" note.
import { chmodSync, copyFileSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, symlinkSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import pkg from "../package.json" with { type: "json" };

const ROOT = join(import.meta.dir, "..");
const DIST = join(ROOT, "dist");
const VERSION = pkg.version;
const APP_NAME = "Universal Wisdom Library";
const ICONS = join(ROOT, "assets", "icon");

const TARGETS: Record<string, { os: "windows" | "macos" | "linux"; arch: string }> = {
  "bun-windows-x64": { os: "windows", arch: "x64" },
  "bun-darwin-arm64": { os: "macos", arch: "arm64" },
  "bun-darwin-x64": { os: "macos", arch: "x64" },
  "bun-linux-x64": { os: "linux", arch: "x64" },
  "bun-linux-arm64": { os: "linux", arch: "arm64" },
};

const arg = (name: string) => process.argv.find((a) => a.startsWith(`--${name}=`))?.slice(name.length + 3) ?? "";
const shouldPackage = process.argv.includes("--package");
const native = `bun-${process.platform === "win32" ? "windows" : process.platform}-${process.arch}`;
const requested = arg("target") || native;
const targets = requested === "all" ? Object.keys(TARGETS) : requested.split(",").map((t) => t.trim()).filter(Boolean);
for (const t of targets) {
  if (!TARGETS[t]) {
    console.error(`Unknown target ${t}. Known: ${Object.keys(TARGETS).join(", ")}`);
    process.exit(1);
  }
}

async function run(cmd: string[], env: Record<string, string> = {}, cwd = ROOT) {
  const proc = Bun.spawn(cmd, { cwd, env: { ...process.env, ...env }, stdout: "inherit", stderr: "inherit" });
  if ((await proc.exited) !== 0) throw new Error(`${cmd.join(" ")} failed`);
}

// 1. The production web client.
await run(["bun", "run", "scripts/build.ts"], { NODE_ENV: "production" });

// 2. While compiling, scripts/app-client-assets.ts embeds every file in public/.
//    It is put back to the empty stand-in afterwards, even on failure.
const PUBLIC = join(ROOT, "public");
function walk(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    return statSync(full).isDirectory() ? walk(full) : [full];
  });
}
const clientFiles = walk(PUBLIC);
const ASSETS_MODULE = join(ROOT, "scripts", "app-client-assets.ts");
const stub = readFileSync(ASSETS_MODULE, "utf8");
const embedModule = [
  "// Generated by scripts/build-app.ts for the duration of a build.",
  ...clientFiles.map((f, i) => `import f${i} from ${JSON.stringify(f)} with { type: "file" };`),
  `export const files: Record<string, string> = {`,
  ...clientFiles.map((f, i) => `  ${JSON.stringify("/" + relative(PUBLIC, f).split("\\").join("/"))}: f${i},`),
  `};`,
  "",
].join("\n");

const FIRST_RUN = `The first start downloads the library (about 3 GB) and unpacks it. Your
web browser opens straight away and shows the progress; you need about 11 GB
of free disk space while it installs and 7 GB after. If the download is
interrupted, open the app again and it carries on where it stopped. After that
it opens in a few seconds.

The library runs only on this computer, in your web browser. It stops by
itself a few minutes after you close its browser tab; open the app again to
come back. Opening it twice is harmless: the second time just brings the page
back.`;

