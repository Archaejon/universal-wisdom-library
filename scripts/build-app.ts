function infoPlist() {
  const version = VERSION.replace(/[^0-9.]/g, "");
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key><string>${APP_NAME}</string>
  <key>CFBundleDisplayName</key><string>${APP_NAME}</string>
  <key>CFBundleIdentifier</key><string>org.universalwisdomlibrary.app</string>
  <key>CFBundleExecutable</key><string>${APP_NAME}</string>
  <key>CFBundleIconFile</key><string>icon</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleShortVersionString</key><string>${version}</string>
  <key>CFBundleVersion</key><string>${version}</string>
  <key>LSMinimumSystemVersion</key><string>13.0</string>
  <!-- No window of its own: it runs in the background and shows itself in the browser. -->
  <key>LSUIElement</key><true/>
  <key>NSHighResolutionCapable</key><true/>
</dict>
</plist>
`;
}

mkdirSync(DIST, { recursive: true });
writeFileSync(ASSETS_MODULE, embedModule);
try {
  for (const target of targets) {
    const { os, arch } = TARGETS[target];
    const name = `UniversalWisdomLibrary-${VERSION}-${os}-${arch}`;
    const folder = join(DIST, name);
    rmSync(folder, { recursive: true, force: true });
    mkdirSync(folder, { recursive: true });

    const appBundle = join(folder, `${APP_NAME}.app`);
    const outfile =
      os === "windows" ? join(folder, `${APP_NAME}.exe`)
      : os === "macos" ? join(appBundle, "Contents", "MacOS", APP_NAME)
      : join(folder, APP_NAME);
    mkdirSync(join(outfile, ".."), { recursive: true });

    const cmd = [
      "bun", "build", join(ROOT, "scripts", "app.ts"),
      "--compile", `--target=${target}`, `--outfile=${outfile}`, "--minify",
      // The bundler fixes process.env.NODE_ENV at build time; the app is always production.
      `--define=process.env.NODE_ENV="production"`,
    ];
    if (os === "windows") {
      if (process.platform === "win32") {
        // Icon, details and no console window: only possible when building on Windows.
        cmd.push(
          "--windows-hide-console",
          `--windows-icon=${join(ICONS, "icon.ico")}`,
          `--windows-title=${APP_NAME}`,
          `--windows-publisher=${APP_NAME}`,
          `--windows-version=${VERSION.replace(/[^0-9.]/g, "")}.0`,
          `--windows-description=${APP_NAME}`,
        );
      } else {
        console.warn("  (Built on non-Windows: the .exe has no icon and opens a console window. Release builds run on Windows.)");
      }
    }
    console.log(`Compiling ${target}…`);
    await run(cmd);
    if (os !== "windows") chmodSync(outfile, 0o755);

    if (os === "macos") {
      mkdirSync(join(appBundle, "Contents", "Resources"), { recursive: true });
      copyFileSync(join(ICONS, "icon.icns"), join(appBundle, "Contents", "Resources", "icon.icns"));
      writeFileSync(join(appBundle, "Contents", "Info.plist"), infoPlist());
      // Apple Silicon refuses to run an unsigned program; an ad-hoc signature is
      // enough to run (Gatekeeper still asks once). Only possible on a Mac.
      if (process.platform === "darwin") await run(["codesign", "--force", "--deep", "--sign", "-", appBundle]);
    }
    writeFileSync(join(folder, "READ ME FIRST.txt"), README[os].replace(/\n/g, os === "windows" ? "\r\n" : "\n"));
    console.log(`  ${relative(ROOT, outfile)} (${(statSync(outfile).size / 1e6).toFixed(0)} MB)`);

    if (!shouldPackage) continue;
    if (os === "linux") {
      await run(["tar", "-czf", `${name}.tar.gz`, name], {}, DIST);
      console.log(`  dist/${name}.tar.gz`);
    } else if (os === "macos" && process.platform === "darwin") {
      // A disk image with the app and a shortcut to Applications to drag it onto.
      symlinkSync("/Applications", join(folder, "Applications"));
      const dmg = join(DIST, `${name}.dmg`);
      rmSync(dmg, { force: true });
      await run(["hdiutil", "create", "-volname", APP_NAME, "-srcfolder", folder, "-ov", "-format", "UDZO", dmg]);
      console.log(`  dist/${name}.dmg`);
    } else {
      // Windows (the setup program is built separately) and macOS built elsewhere.
      rmSync(join(DIST, `${name}.zip`), { force: true });
      await run(["zip", "-qry", `${name}.zip`, name], {}, DIST);
      console.log(`  dist/${name}.zip`);
    }
  }
} finally {
  writeFileSync(ASSETS_MODULE, stub);
}
