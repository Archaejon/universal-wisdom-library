type Row = Record<string, any>;

export type StreamEditionConfig = {
  slug: string;
  language: string;
  languageName: string;
  version: string;
  license: string;
  sourceUrl: string;
};

export type StreamWork = {
  slug: string;
  provider: string;
  upstream: string;
  mode: "numbered" | "complex";
  licence: string;
  editions: StreamEditionConfig[];
  config: Record<string, any>;
};

export type StreamedEdition = {
  slug: string;
  /** One entry per upstream segment, aligned with the chapter's passage index. */
  segments: string[];
  versionTitle: string;
  versionTitleHebrew: string;
  language: string;
  license: string;
  sourceUrl: string;
  /** True when the pinned edition title was served; false when upstream fell back. */
  pinned: boolean;
  error?: string;
};

export type StreamedChapter = {
  provider: string;
  upstream: string;
  upstreamRef: string;
  upstreamUrl: string;
  fetchedAt: string;
  editions: StreamedEdition[];
  /** The upstream segmentation matches the locally indexed passage count. */
  aligned: boolean;
  cached: boolean;
  notice: string;
  /**
   * The chapter holds more verses than this read addressed, and the first
   * `servedVerses` of them are the ones the chapter carries. The reader lists
   * those rather than a chapter outline it cannot fill.
   */
  servedVerses?: number;
};

