async function fetchAlQuran(
  work: StreamWork,
  chapter: { ref: string; label: string },
  expected: number,
): Promise<StreamedChapter | null> {
  const out: StreamedEdition[] = [];
  for (const edition of work.editions) {
    const url = `https://api.alquran.cloud/v1/surah/${encodeURIComponent(chapter.ref)}/${encodeURIComponent(edition.version)}`;
    try {
      const { body } = await fetchJson(url, { timeoutMs: 20_000 });
      const ayahs = body?.data?.ayahs;
      if (!Array.isArray(ayahs)) throw new Error(body?.data ?? "unexpected response");
      const segments = ayahs.map((a: any) => stripMarkup(String(a.text ?? "")));
      out.push({
        slug: edition.slug,
        segments,
        versionTitle: edition.version,
        versionTitleHebrew: "",
        language: edition.language,
        license: edition.license,
        sourceUrl: "https://alquran.cloud/",
        pinned: true,
      });
    } catch (err) {
      out.push({
        slug: edition.slug,
        segments: [],
        versionTitle: edition.version,
        versionTitleHebrew: "",
        language: edition.language,
        license: edition.license,
        sourceUrl: "https://alquran.cloud/",
        pinned: true,
        error: (err as Error).message,
      });
    }
  }
  const usable = out.filter((e) => e.segments.length > 0);
  if (!usable.length) return null;
  const aligned = usable.some((e) => e.segments.length === expected);
  return {
    provider: "alquran-cloud",
    upstream: work.upstream,
    upstreamRef: `Surah ${chapter.ref}`,
    upstreamUrl: `https://quran.com/${chapter.ref}`,
    fetchedAt: new Date().toISOString(),
    editions: out,
    aligned,
    cached: false,
    notice: aligned ? "" : `The hosted source returned ${usable[0].segments.length} ayahs for this surah.`,
  };
}

// ---------------------------------------------------------------------------
// Quran.com tafsir resources
// ---------------------------------------------------------------------------
//
// Classical commentaries in Arabic, one ayah at a time. The library indexes
// the surahs and ayahs from its own Qur'an edition; this provider asks the
// hosted tafsir resource for the same surah and returns one segment per ayah.
// The Arabic works are public domain; the digital text comes from Quran.com.

/** Turn a tafsir HTML fragment into plain paragraphs without losing breaks. */
export const TAFSIR_GAP_MARKER = "لا يتضمن مورد Quran.com تعليقًا";

function tafsirParagraphs(html: string): string {
  return String(html)
    .split(/<\/(?:p|div|h[1-6]|li)>|<br\s*\/?>/i)
    .map((chunk) => stripMarkup(chunk))
    .filter(Boolean)
    .join("\n\n");
}

async function fetchQuranTafsir(
  work: StreamWork,
  chapter: { ref: string; label: string },
  expected: number,
): Promise<StreamedChapter | null> {
  const resourceId = Number(work.config?.resourceId);
  if (!Number.isFinite(resourceId)) return null;
  const url = `https://api.quran.com/api/v4/tafsirs/${resourceId}/by_chapter/${encodeURIComponent(chapter.ref)}?per_page=300`;
  const out: StreamedEdition[] = [];
  let gapsReported = 0;
  for (const edition of work.editions) {
    try {
      const { body } = await fetchJson(url, { timeoutMs: 60_000 });
      const entries = Array.isArray(body?.tafsirs) ? body.tafsirs : [];
      if (!entries.length) throw new Error("Quran.com returned no commentary for this surah");
      // Place each commentary at its own ayah. A resource may skip an ayah, and
      // positional pairing would then shift every later verse; a marked gap is
      // better than a silent misalignment.
      const segments = new Array<string>(expected).fill("");
      for (const entry of entries) {
        const ayah = Number(String(entry?.verse_key ?? "").split(":").pop());
        if (!Number.isInteger(ayah) || ayah < 1 || ayah > expected) continue;
        const text = tafsirParagraphs(String(entry?.text ?? ""));
        if (text) segments[ayah - 1] = text;
      }
      const gaps = segments.filter((text) => !text).length;
      if (gaps === expected) throw new Error("Quran.com returned no usable commentary for this surah");
      for (let i = 0; i < segments.length; i++) {
        if (!segments[i]) {
          segments[i] = `${TAFSIR_GAP_MARKER} على الآية ${chapter.ref}:${i + 1}.`;
        }
      }
      gapsReported = gaps;
      out.push({
        slug: edition.slug,
        segments,
        versionTitle: edition.version,
        versionTitleHebrew: "",
        language: edition.language,
        license: edition.license,
        sourceUrl: edition.sourceUrl || "https://quran.com/",
        pinned: true,
      });
    } catch (err) {
      out.push({
        slug: edition.slug,
        segments: [],
        versionTitle: edition.version,
        versionTitleHebrew: "",
        language: edition.language,
        license: edition.license,
        sourceUrl: edition.sourceUrl || "https://quran.com/",
        pinned: true,
        error: (err as Error).message,
      });
    }
  }
  const usable = out.filter((e) => e.segments.length > 0);
  if (!usable.length) return null;
  const aligned = usable.some((e) => e.segments.length === expected);
  return {
    provider: "quran-tafsir",
    upstream: work.upstream,
    upstreamRef: `Surah ${chapter.ref}`,
    upstreamUrl: `https://quran.com/${chapter.ref}`,
    fetchedAt: new Date().toISOString(),
    editions: out,
    aligned,
    cached: false,
    notice: gapsReported
      ? `Quran.com includes no commentary for ${gapsReported} ayah${gapsReported === 1 ? "" : "s"} of this surah; those ayahs are marked in the text.`
      : "",
  };
}

// ---------------------------------------------------------------------------
// Bolls Bible API
// ---------------------------------------------------------------------------
//
// One chapter of a Bible book per request. The library indexes a book's
// chapters and verses; the verse text is fetched here, not stored.

async function fetchBolls(
  work: StreamWork,
  chapter: { ref: string; label: string },
  expected: number,
): Promise<StreamedChapter | null> {
  const out: StreamedEdition[] = [];
  for (const edition of work.editions) {
    const url = `https://bolls.life/get-chapter/${encodeURIComponent(edition.version)}/${encodeURIComponent(
      work.upstream,
    )}/${encodeURIComponent(chapter.ref)}/`;
    try {
      const { body } = await fetchJson(url, { timeoutMs: 25_000 });
      if (!Array.isArray(body)) throw new Error("Bolls returned no verse list");
      const verses = [...body].sort((a: any, b: any) => Number(a?.verse ?? 0) - Number(b?.verse ?? 0));
      const segments = verses.map((v: any) => stripMarkup(String(v?.text ?? "")));
      out.push({
        slug: edition.slug,
        segments,
        versionTitle: edition.version,
        versionTitleHebrew: "",
        language: edition.language,
        license: edition.license,
        sourceUrl: edition.sourceUrl,
        pinned: true,
      });
    } catch (err) {
      out.push({
        slug: edition.slug,
        segments: [],
        versionTitle: edition.version,
        versionTitleHebrew: "",
        language: edition.language,
        license: edition.license,
        sourceUrl: edition.sourceUrl,
        pinned: true,
        error: (err as Error).message,
      });
    }
  }
  const usable = out.filter((e) => e.segments.length > 0);
  if (!usable.length) return null;
  const aligned = usable.some((e) => e.segments.length === expected);
  return {
    provider: "bolls",
    upstream: work.upstream,
    upstreamRef: `${work.editions[0]?.version ?? "KJV"} ${work.upstream}:${chapter.ref}`,
    upstreamUrl: `https://bolls.life/${encodeURIComponent(work.editions[0]?.version ?? "KJV")}/${work.upstream}/${chapter.ref}/`,
    fetchedAt: new Date().toISOString(),
    editions: out,
    aligned,
    cached: false,
    notice: aligned ? "" : `The hosted edition returns ${usable[0].segments.length} verses for this chapter; the library indexed ${expected}.`,
  };
}

// ---------------------------------------------------------------------------
// HTML hosts (Christian Classics Ethereal Library, New Advent)
// ---------------------------------------------------------------------------

export type HtmlSegmentation = {
  /** Marker that opens the text container in the hosted page. */
  startMarker: string;
  /** Marker that closes the text container. */
  endMarker: string;
  /**
   * Paragraphs are one segment each; articles begin at an `<h2>` that names an
   * article (Summa); sections begin at any `<h2>` (the City of God chapters);
   * blocks cut a plain-text transcription into its printed chapters.
   */
  split: "paragraphs" | "articles" | "sections" | "blocks";
  /**
   * Printed page numbers ("p. 12") interrupt the running text in the Sacred
   * Books of the East transcriptions. They are page furniture, so a volume that
   * asks for this drops them before the passage index is built.
   */
  dropPageNumbers?: boolean;
  /**
   * Some volumes of the Chinese Classics were transcribed without markup, as
   * one long `<PRE>` block of hard-wrapped lines. For those, a segment opens at
   * a line matching this pattern (Legge's "CHAPTER I. 1. The Master said" or the
   * bilingual pagination's "【第一章】") and runs to the next such line.
   */
  blockPattern?: string;
  /**
   * A line that closes the block it is printed in and opens nothing: the book
   * heading above a numbered chapter, which is not part of the chapter below it.
   */
  blockDropPattern?: string;
  /**
   * A line that is dropped without closing the block it stands in: the Chinese
   * titles a bilingual page prints beside its English ones.
   */
  blockSkipPattern?: string;
  /**
   * Keep only the blocks whose opening line matches this pattern. A bilingual
   * page prints the original and the translation in one block sequence, so the
   * edition that reads the original keeps the blocks that open at its own
   * chapter markers.
   */
  blockKeepPattern?: string;
};

export function sliceHtml(html: string, startMarker: string, endMarker: string): string {
  const start = startMarker ? html.indexOf(startMarker) : 0;
  if (start < 0) return "";
  const from = start + startMarker.length;
  const end = endMarker ? html.indexOf(endMarker, from) : -1;
  return end > from ? html.slice(from, end) : html.slice(from);
}

// "end" and "end of part one" are the ruled dividers a publication sets at the
// close of a part or a work; they are furniture, not paragraphs of the text.
const NOISE = /^(?:«?\s*prev|next\s*»?|contents|table of contents|index(?:es)?|home|title page|preface|the end|finis|end|end of part (?:one|two|three|four|[ivxlcdm]+|\d+)|«|»)[\s.:]*$/i;

// The Sacred Books of the East transcriptions print page numbers as "p. 12",
// "{p. 12}" or with a roman numeral, and separate sections with rules made of
// underscores or dashes. Neither is part of the text.
// Some volumes (Griffith's Atharvaveda) print a letter with the page number
// ("p. a1"); the letter belongs to the page, not the text.
const PAGE_NUMBER = /^[{[]?\s*p{1,2}\.\s*(?:[a-z]?\d+|[ivxlcdm]+)\s*[}\]]?$/i;
const PAGE_NUMBER_RUN = /^(?:[{[]?\s*p{1,2}\.\s*(?:[a-z]?\d+|[ivxlcdm]+)\s*[}\]]?\s*)+$/i;
// A page that opens mid-title leaves a fragment such as "OF" above the text,
// and the printed running head "Translation." repeats on every page.
const TITLE_FRAGMENT = /^(?:[A-Z]{1,3}|Translation\.)$/;
const RULE = /^[_\-=~*·—–]{3,}$/;

function isPageFurniture(text: string): boolean {
  return PAGE_NUMBER.test(text) || PAGE_NUMBER_RUN.test(text) || RULE.test(text) || TITLE_FRAGMENT.test(text);
}

// A Han character: the source-text half of a bilingual transcription is the
// only half that carries them.
export const HAN = /[\u3400-\u4dbf\u4e00-\u9fff\uf900-\ufaff\u3000-\u303f]/;

/**
 * The plain text of a `<PRE>` transcription, with its line breaks intact: the
 * blocks are found by line, so the whitespace cannot be collapsed first.
 */
function preText(fragment: string): string {
  const pre = /<pre[^>]*>([\s\S]*?)<\/pre>/i.exec(fragment);
  const inner = pre ? pre[1] ?? "" : fragment;
  return inner
    .replace(/<br\s*\/?>/gi, "\n")
    .replace(/<[^>]*>/g, "")
    .replace(/&nbsp;/g, " ")
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&#39;|&apos;/g, "'")
    .replace(/&#x([0-9a-f]+);/gi, (_, hex: string) => String.fromCodePoint(parseInt(hex, 16)))
    .replace(/&#(\d+);/g, (_, dec: string) => String.fromCodePoint(Number(dec)));
}

/**
 * One cut of a plain-text page: the block's text, and whether the line that
 * closed it was a heading the work keeps out of its chapters.
 */
export type BlockCut = { text: string; dropped: boolean };

const asPattern = (source: string | undefined): RegExp | null => {
  if (!source) return null;
  try {
    return new RegExp(source, "i");
  } catch {
    return null;
  }
};

/**
 * Cut a plain-text page into the blocks its printed chapters begin with. A page
 * with no pattern of its own is cut at its blank lines, which is how a
 * transcription of continuous prose separates its paragraphs. The matter above
 * the first block (the volume's title, the translator's preface) is not part of
 * the work and is dropped.
 */
export function cutBlocks(
  fragment: string,
  blockPattern: string,
  options: { dropPattern?: string; skipPattern?: string; keepPattern?: string } = {},
): BlockCut[] {
  const open = asPattern(blockPattern);
  const drop = asPattern(options.dropPattern);
  const skip = asPattern(options.skipPattern);
  const keep = asPattern(options.keepPattern);
  const out: BlockCut[] = [];
  let current: string[] | null = null;
  const flush = (dropped: boolean) => {
    if (!current) return;
    const opener = current[0] ?? "";
    const text = current.join(" ").replace(/\s+/g, " ").trim();
    current = null;
    if (text.length < 2) return;
    if (keep && !keep.test(opener)) return;
    out.push({ text, dropped });
  };
  for (const raw of preText(fragment).split(/\r?\n/)) {
    const line = raw.trim();
    if (!line) {
      // Without a pattern to open blocks, a blank line is what separates them.
      if (!open) flush(false);
      continue;
    }
    if (drop?.test(line)) {
      // The heading closes the block it stands after and is reported as its
      // own cut, so a caller can group the chapters under it.
      flush(false);
      out.push({ text: line, dropped: true });
      continue;
    }
    if (open?.test(line)) {
      flush(false);
      current = [line];
      continue;
    }
    if (skip?.test(line)) continue;
    // A block that never opens at a marker — the blank-line page — begins with
    // the page's first real line.
    if (!open && !current) current = [line];
    else if (current) current.push(line);
  }
  flush(false);
  return out;
}

function blockTexts(fragment: string, config: HtmlSegmentation): string[] {
  return cutBlocks(fragment, config.blockPattern ?? "", {
    dropPattern: config.blockDropPattern,
    skipPattern: config.blockSkipPattern,
    keepPattern: config.blockKeepPattern,
  })
    .filter((block) => !block.dropped)
    .map((block) => block.text);
}

function paragraphTexts(fragment: string, dropPageNumbers = false): string[] {
  const out: string[] = [];
  for (const match of fragment.matchAll(/<p\b([^>]*)>([\s\S]*?)<\/p>/gi)) {
    const attrs = match[1] ?? "";
    // Running heads, page numbers and footnote blocks are page furniture.
    if (/class="[^"]*(?:footnote|footnotes|nav|navbar|page)\b/i.test(attrs)) continue;
    const text = stripMarkup(match[2]);
    if (text.length < 2 || /^\d+$/.test(text) || NOISE.test(text)) continue;
    if (dropPageNumbers && isPageFurniture(text)) continue;
    out.push(text);
  }
  return out;
}

/** Split a hosted page into the segments the passage index was built from. */
export function extractHtmlSegments(html: string, config: HtmlSegmentation): string[] {
  // Sacred Text Archive pages print the verse number in a marginal-note span
  // that sits directly against the first word ("<span …>1</span>Now may…").
  // Keeping the number but padding it stops the text running together.
  let fragment = sliceHtml(html, config.startMarker, config.endMarker).replace(
    /<span[^>]*class="[^"]*margnote[^"]*"[^>]*>([\s\S]*?)<\/span>/gi,
    " $1 ",
  );
  // Some transcriptions print the page number inside the running paragraph
  // (Carus's Canon of Reason and Virtue breaks a sentence with "p. 76" in the
  // middle of it). The archive anchors every such number as page_N, so a
  // volume that drops page numbers drops the anchor and the number with it.
  if (config.dropPageNumbers) {
    fragment = fragment.replace(/\s*<a\b[^>]*name="page_[^"]*"[^>]*>[\s\S]*?<\/a>/gi, " ");
  }
  if (!fragment) return [];
  if (config.split === "blocks") {
    return blockTexts(fragment, config);
  }
  if (config.split === "paragraphs") {
    const paragraphs = paragraphTexts(fragment, config.dropPageNumbers);
    if (paragraphs.length) return paragraphs;
    // A few printed pages are stubs: a heading and a cross-reference, with no
    // paragraph of their own (Yasna LXIV in SBE 31 is one). The heading is the
    // page's only text, so it is kept rather than reported as an empty chapter.
    const headings = [...fragment.matchAll(/<h[1-4][^>]*>([\s\S]*?)<\/h[1-4]>/gi)]
      .map((match) => stripMarkup(match[1]))
      .filter((text) => text.length > 1);
    return headings.length ? [headings.join(" ")] : [];
  }
  // New Advent marks each article with <h2 id="articleN">; the City of God
  // uses a plain <h2> for each chapter. The heading opens each segment.
  const pattern = config.split === "articles" ? /<h2[^>]*id="article\d+"[^>]*>([\s\S]*?)<\/h2>/gi : /<h2[^>]*>([\s\S]*?)<\/h2>/gi;
  const headings = [...fragment.matchAll(pattern)];
  const segments: string[] = [];
  for (const [index, heading] of headings.entries()) {
    const from = (heading.index ?? 0) + heading[0].length;
    const to = index + 1 < headings.length ? headings[index + 1].index ?? fragment.length : fragment.length;
    const title = stripMarkup(heading[1]);
    const body = paragraphTexts(fragment.slice(from, to), config.dropPageNumbers).join("\n\n");
    const text = [title, body].filter(Boolean).join(" — ");
    if (text) segments.push(text);
  }
  return segments;
}

async function fetchHtmlText(url: string): Promise<string> {
  let lastError: Error | null = null;
  for (let attempt = 1; attempt <= 3; attempt++) {
    try {
      const res = await fetch(url, {
        headers: {
          accept: "text/html",
          "user-agent": "UniversalWisdomLibrary/1.0 (local reading interface; streamed text)",
        },
        signal: AbortSignal.timeout(30_000),
      });
      if (res.status === 429 || res.status >= 500) {
        lastError = new Error(`${url} returned ${res.status}`);
        await Bun.sleep(500 * attempt * attempt);
        continue;
      }
      if (!res.ok) throw new Error(`${url} returned ${res.status}`);
      return await res.text();
    } catch (err) {
      lastError = err as Error;
      if (attempt < 3) await Bun.sleep(400 * attempt);
    }
  }
  throw lastError ?? new Error(`${url} failed`);
}

type HtmlPageEntry = {
  title?: string;
  url: string;
  startMarker?: string;
  endMarker?: string;
  /**
   * A work printed as one long page is indexed as several chapters, each a
   * slice of the page's segments. The slice is recorded at import time so the
   * reader reproduces exactly the passage range the index was built from.
   */
  from?: number;
  to?: number;
};
/**
 * A second edition of the same work read from its own page. A bilingual volume
 * prints the original and the translation on one page, so an edition that takes
 * the original carries its own page list and its own way of cutting the page
 * into passages.
 */
type HtmlEditionConfig = Partial<Pick<HtmlSegmentation, "split" | "blockPattern" | "blockDropPattern" | "blockSkipPattern" | "blockKeepPattern" | "startMarker" | "endMarker">> & {
  pages?: (string | HtmlPageEntry)[];
};
type HtmlConfig = HtmlSegmentation & {
  pageBase?: string;
  pages: (string | HtmlPageEntry)[];
  editions?: Record<string, HtmlEditionConfig>;
};

async function fetchHtmlWork(
  work: StreamWork,
  chapter: { ref: string; label: string },
  expected: number,
): Promise<StreamedChapter | null> {
  const config = work.config as HtmlConfig;
  const index = Number(chapter.ref) - 1;
  // A page list holds either addresses or { title, url } records, so an import
  // that records the page title can share this reader.
  const pageAt = (pages: (string | HtmlPageEntry)[] | undefined) => {
    const entry = pages?.[index] as unknown;
    const record = typeof entry === "string" ? null : (entry as HtmlPageEntry | undefined);
    const page = typeof entry === "string" ? entry : record?.url ?? "";
    return page ? { record, url: /^https?:\/\//.test(page) ? page : `${config.pageBase ?? ""}${page}` } : null;
  };
  const primary = pageAt(config.pages);
  if (!primary) return null;

  const pages = new Map<string, { html: string; error?: string }>();
  const fetchPage = async (url: string) => {
    const cached = pages.get(url);
    if (cached) return cached;
    let value: { html: string; error?: string };
    try {
      value = { html: await fetchHtmlText(url) };
    } catch (err) {
      value = { html: "", error: (err as Error).message };
    }
    pages.set(url, value);
    return value;
  };

  const fetched = await fetchPage(primary.url);
  const out: StreamedEdition[] = [];
  for (const edition of work.editions) {
    const override = config.editions?.[edition.slug];
    const page = override ? pageAt(override.pages) ?? primary : primary;
    const source = page === primary ? fetched : await fetchPage(page.url);
    // A volume can mix two transcriptions whose text begins under a different
    // rule, so a page may carry its own opening marker.
    const segmentation: HtmlSegmentation = {
      ...config,
      ...(override ?? {}),
      ...(page.record?.startMarker ? { startMarker: page.record.startMarker } : {}),
      ...(page.record?.endMarker ? { endMarker: page.record.endMarker } : {}),
    };
    let segments = source.html ? extractHtmlSegments(source.html, segmentation) : [];
    if (page.record && typeof page.record.from === "number") {
      segments = segments.slice(page.record.from, page.record.to ?? segments.length);
    }
    out.push({
      slug: edition.slug,
      segments,
      versionTitle: edition.version,
      versionTitleHebrew: "",
      language: edition.language,
      license: edition.license,
      sourceUrl: edition.sourceUrl,
      pinned: true,
      error: segments.length ? undefined : source.error ?? "The hosted page returned no text",
    });
  }
  const usable = out.filter((e) => e.segments.length > 0);
  if (!usable.length) return null;
  const aligned = usable.some((e) => e.segments.length === expected);
  return {
    provider: work.provider,
    upstream: work.upstream,
    upstreamRef: chapter.label,
    upstreamUrl: primary.url,
    fetchedAt: new Date().toISOString(),
    editions: out,
    aligned,
    cached: false,
    notice: aligned
      ? ""
      : `The hosted page now yields ${usable[0].segments.length} segments for this chapter where the library indexed ${expected}. The text is shown as received.`,
  };
}

// ---------------------------------------------------------------------------
// Hadith API (fawazahmed0/hadith-api, served from jsDelivr)
// ---------------------------------------------------------------------------
//
// Each collection is addressed by book and section: one JSON document per
// section, the hadiths in that section in order. The Arabic and English
// editions use the same section numbering, so the two panes line up.

async function fetchHadith(
  work: StreamWork,
  chapter: { ref: string; label: string },
  expected: number,
): Promise<StreamedChapter | null> {
  const out: StreamedEdition[] = [];
  for (const edition of work.editions) {
    const url = `https://cdn.jsdelivr.net/gh/fawazahmed0/hadith-api@1/editions/${encodeURIComponent(
      edition.version,
    )}/sections/${encodeURIComponent(chapter.ref)}.min.json`;
    try {
      const { body } = await fetchJson(url, { timeoutMs: 30_000 });
      const hadiths = Array.isArray(body?.hadiths) ? body.hadiths : [];
      const segments = [...hadiths]
        .sort((a: any, b: any) => Number(a?.hadithnumber ?? 0) - Number(b?.hadithnumber ?? 0))
        .map((h: any) => stripMarkup(String(h?.text ?? "")))
        .filter((text: string) => text.length > 0);
      out.push({
        slug: edition.slug,
        segments,
        versionTitle: edition.version,
        versionTitleHebrew: "",
        language: edition.language,
        license: edition.license,
        sourceUrl: url,
        pinned: true,
        error: segments.length ? undefined : `The API returned no ${edition.language} hadiths for this section`,
      });
    } catch (err) {
      out.push({
        slug: edition.slug,
        segments: [],
        versionTitle: edition.version,
        versionTitleHebrew: "",
        language: edition.language,
        license: edition.license,
        sourceUrl: url,
        pinned: true,
        error: (err as Error).message,
      });
    }
  }
  const usable = out.filter((e) => e.segments.length > 0);
  if (!usable.length) return null;
  const aligned = usable.some((e) => e.segments.length === expected);
  return {
    provider: "hadith",
    upstream: work.upstream,
    upstreamRef: `${work.upstream} ${chapter.ref}`,
    upstreamUrl: `https://cdn.jsdelivr.net/gh/fawazahmed0/hadith-api@1/editions/eng-${work.upstream}/sections/${chapter.ref}.min.json`,
    fetchedAt: new Date().toISOString(),
    editions: out,
    aligned,
    cached: false,
    notice: aligned
      ? ""
      : `The hosted section now holds ${usable[0].segments.length} hadiths where the library indexed ${expected}. The text is shown as received.`,
  };
}

