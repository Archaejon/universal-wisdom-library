// ---------------------------------------------------------------------------
// sacred-texts.com — the archive's current site
// ---------------------------------------------------------------------------
//
// The Internet Sacred Text Archive now serves each printed chapter of a volume
// as a reading view whose data arrives as one JSON document (`<view>/__data.json`,
// a SvelteKit payload of flattened references). The view's `chapterContent`
// holds the chapter as a single HTML string: a heading or two, the paragraphs of
// the translation, and the marks of the printed page the scan was taken from. A
// printed page number stands in the text where the page turned, a run of empty
// paragraphs sits around it, and the paragraph it interrupts continues on the
// far side. Those numbers and blanks are furniture of the scan rather than text,
// so they are dropped here and a paragraph the turn cut in two is joined back
// into one before the chapter is shown.
//
// The translator's footnotes are the volume's apparatus, not its scripture:
// their markers are removed from the text and the notes themselves are not
// carried, which the edition record says.

export type SacredTextsPage = {
  segments: string[];
  /** The chapter's printed headings, in order, withdrawn from the text. */
  headings: string[];
  /** The printed page numbers the scan carried inline, in order. */
  pages: number[];
  /** Paragraphs a page turn cut in two, rejoined into one. */
  rejoined: number;
};

/**
 * The archive marks a footnote with a link to the volume's note, both inside a
 * chapter and across from one view to the next; the note is the volume's
 * apparatus and its marker is removed with it.
 */
const FOOTNOTE_MARK = /<a\b[^>]*(?:data-footnote-ref|#fn[-_])[^>]*>[\s\S]*?<\/a>/gi;

/** A paragraph ends here, so a page turn after it did not cut it in two. */
const TERMINAL = /[.!?:;"”’'’)\]]$/;

function joinsAcrossPage(previous: string, next: string): boolean {
  if (TERMINAL.test(previous)) return false;
  // A word hyphenated over the page turn is put back together without the
  // hyphen; anything else is rejoined with a space, and only where the next
  // line plainly continues in lower case rather than opening a new paragraph.
  if (/-$/.test(previous)) return /^[a-zà-ÿ]/.test(next);
  return /^[a-zà-ÿ(“"']/.test(next);
}

/**
 * One reading view of the archive, cleaned for the reader.
 */
export function sacredTextsPage(html: string): SacredTextsPage {
  // The view ends its chapter with a rule; what follows is the page's own
  // furniture rather than part of the printed text.
  const body = String(html).split(/<hr\b/i)[0] ?? "";
  const segments: string[] = [];
  const headings: string[] = [];
  const pages: number[] = [];
  let rejoined = 0;
  let broken = false;
  for (const block of body.matchAll(/<(h[1-6]|p)\b[^>]*>([\s\S]*?)<\/\1>/gi)) {
    const tag = (block[1] ?? "p").toLowerCase();
    // The archive marks each footnote with a link in the text; the marker goes
    // with the note, which is not carried. Italics stay: they carry Jacobi's
    // transliteration marks, and without them the words read differently.
    // Removing a footnote marker leaves the space the page put before it, and a
    // comma standing after a space is the one mark of the scan left in the text.
    const text = stripMarkup((block[2] ?? "").replace(FOOTNOTE_MARK, " "))
      .replace(/\s+([,.;:!?)\]])(?![\d])/g, "$1");
    if (tag !== "p") {
      if (text) headings.push(text);
      // A heading ends the paragraph before it, whatever the run of page marks.
      broken = false;
      continue;
    }
    // A page number stands where the page turned, and a turn between two
    // printed pages can leave two numbers in one paragraph ("p. 216 p. 217").
    if (/^p\.\s*\d+(?:\s+p\.\s*\d+)*$/i.test(text)) {
      for (const number of text.matchAll(/p\.\s*(\d+)/gi)) pages.push(Number(number[1]));
      broken = true;
      continue;
    }
    // A rule the printer drew as a line of underscores or dashes is a mark of
    // the page, not a sentence of the text.
    if (/^[_.*~=+-]{4,}$/.test(text)) continue;
    // The scan's blank lines arrive as paragraphs holding a space.
    if (!text) continue;
    const previous = segments.at(-1);
    if (broken && previous && joinsAcrossPage(previous, text)) {
      segments[segments.length - 1] = /-$/.test(previous)
        ? `${previous.slice(0, -1)}${text}`
        : `${previous} ${text}`;
      rejoined++;
    } else {
      segments.push(text);
    }
    broken = false;
  }
  return { segments, headings, pages, rejoined };
}

/**
 * A SvelteKit `__data.json` payload resolved into plain values. The document is
 * a list of nodes whose last one is the page; its values are stored flat, and a
 * number inside an object or array is the index of the value it stands for.
 */
export function svelteKitData(raw: any): any {
  const nodes = Array.isArray(raw?.nodes) ? raw.nodes : [];
  const data: any[] = nodes[nodes.length - 1]?.data ?? [];
  const memo = new Map<number, any>();
  const resolve = (index: number): any => {
    if (memo.has(index)) return memo.get(index);
    const value = data[index];
    if (Array.isArray(value)) {
      const out: any[] = [];
      memo.set(index, out);
      for (const entry of value) out.push(resolve(entry));
      return out;
    }
    if (value && typeof value === "object") {
      const out: Record<string, any> = {};
      memo.set(index, out);
      for (const [key, entry] of Object.entries(value)) out[key] = resolve(entry as number);
      return out;
    }
    memo.set(index, value);
    return value;
  };
  return data.length ? resolve(0) : null;
}

type SacredTextsJsonConfig = {
  /** The archive's book, e.g. "jaina-sutras-part-i". */
  book: string;
  /** Per chapter: its printed pages, each the tail of a reading view's address. */
  chapters: Record<string, { label: string; pages: string[] }>;
};

const SACRED_TEXTS_SITE = "https://sacred-texts.com";
// The archive sits behind a filter that answers a request from anything but a
// browser with a challenge. curl's stack passes and Bun's own does not, whatever
// headers the request carries, so the reading views are fetched with curl.
const BROWSER_USER_AGENT =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/125.0 Safari/537.36";

/**
 * A URL read through curl, with the status the host answered. Used for the hosts
 * that refuse a non-browser client; a machine without curl raises the error curl
 * could not be started with, which the caller reports rather than hides.
 */
export async function fetchTextWithCurl(
  url: string,
  timeoutMs = 45_000,
): Promise<{ status: number; body: string }> {
  const proc = Bun.spawn(
    [
      "curl", "-sS", "-L", "--max-time", String(Math.ceil(timeoutMs / 1000)),
      "-A", BROWSER_USER_AGENT, "-w", "\n%{http_code}", url,
    ],
    { stdout: "pipe", stderr: "pipe" },
  );
  const [out, err, code] = await Promise.all([
    new Response(proc.stdout).text(),
    new Response(proc.stderr).text(),
    proc.exited,
  ]);
  if (code !== 0) throw new Error(err.trim() || `curl exited ${code}`);
  const cut = out.lastIndexOf("\n");
  return { status: Number(out.slice(cut + 1).trim()) || 0, body: cut >= 0 ? out.slice(0, cut) : out };
}

async function sacredTextsJson(url: string): Promise<{ status: number; data: any }> {
  try {
    const { status, body } = await fetchTextWithCurl(url);
    return { status, data: status === 200 ? JSON.parse(body) : null };
  } catch {
    // Without curl the ordinary client is tried, so a machine that has none
    // still reports the host's own answer rather than only curl's absence.
    const { status, body } = await fetchJson(url, { headers: { "user-agent": BROWSER_USER_AGENT } });
    let data: any = null;
    if (typeof body === "string") {
      try {
        data = JSON.parse(body);
      } catch {
        data = null;
      }
    } else {
      data = body ?? null;
    }
    return { status, data };
  }
}

