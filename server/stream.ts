// Streaming text layer.
//
// A streamed work is not stored in this library. Its catalogue record, chapter
// outline and passage index live in SQLite; the chapter text is requested from
// the project that hosts it and held only in a small in-process cache. Nothing
// fetched here is written to the database or to disk.
