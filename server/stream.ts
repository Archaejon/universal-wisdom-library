let manifest: Map<string, StreamWork> | null = null;

// The manifest is generated by scripts/dev/build-stream-manifest.ts and seeded
// into work_streams, so the reader can resolve a work without loading a file
// from disk on every request.
export function loadStreamManifest(): Map<string, StreamWork> {
  if (manifest) return manifest;
  manifest = new Map();
  try {
    const rows = getDb()
      .query("SELECT work_slug, provider, upstream_id, mode, config_json FROM work_streams")
      .all() as Row[];
    for (const row of rows) {
      const config = JSON.parse(row.config_json || "{}");
      manifest.set(row.work_slug, {
        slug: row.work_slug,
        provider: row.provider,
        upstream: row.upstream_id,
        mode: row.mode === "complex" ? "complex" : "numbered",
        licence: config.licence ?? "",
        editions: Array.isArray(config.editions) ? config.editions : [],
        config,
      });
    }
  } catch {
    // A database that predates the streaming table simply has no streamed works.
  }
  return manifest;
}

export function streamWork(slug: string): StreamWork | null {
  return loadStreamManifest().get(slug) ?? null;
}

export function isStreamed(slug: string): boolean {
  return loadStreamManifest().has(slug);
}

export function streamedWorkCount(): number {
  return loadStreamManifest().size;
}

