type SuttaCentralConfig = { translator: string; rootTranslator: string };

// The bilara endpoint returns one object per translation, keyed by segment id.
async function fetchSuttaCentral(
  work: StreamWork,
  chapter: { ref: string; label: string; labels?: string[] },
  expected: number,
): Promise<StreamedChapter | null> {
  const config = (work.config ?? {}) as SuttaCentralConfig;
  const translator = config.translator ?? "sujato";
  const rootTranslator = config.rootTranslator ?? "sujato";
  const uid = chapter.ref;
  const out: StreamedEdition[] = [];
  for (const edition of work.editions) {
    const isRoot = edition.language === "pi";
    const url = `https://suttacentral.net/api/bilarasuttas/${encodeURIComponent(uid)}/${encodeURIComponent(
      isRoot ? rootTranslator : translator,
    )}?lang=${isRoot ? "pi" : "en"}`;
    try {
      const { body } = await fetchJson(url, { timeoutMs: 30_000 });
      const text = (isRoot ? body?.root_text : body?.translation_text) ?? {};
      // The passage index carries SuttaCentral's segment ids as labels. Using
      // them keeps the Pali and English panes aligned even where one language
      // has no text for a segment.
      const english: Record<string, string> = body?.translation_text ?? {};
      const keys: string[] = chapter.labels?.length
        ? chapter.labels
        : (Array.isArray(body?.keys_order) ? body.keys_order : Object.keys(text)).filter(
            (key: string) => String(english[key] ?? "").trim().length > 0 && !/:0\.\d+$/.test(key),
          );
      const segments = keys.map((key) => stripMarkup(String(text[key] ?? "")));
      out.push({
        slug: edition.slug,
        segments,
        versionTitle: edition.version,
        versionTitleHebrew: "",
        language: edition.language,
        license: edition.license,
        sourceUrl: edition.sourceUrl,
        pinned: true,
        error: segments.length ? undefined : `SuttaCentral returned no ${edition.language} segments`,
      });
    } catch (err) {
      out.push({
        slug: edition.slug,
        segments: [],
        versionTitle: edition.version,
        versionTitleHebrew: "",
        language: edition.language,
        license: edition.license,
        sourceUrl: edition.sourceUrl,
        pinned: true,
        error: (err as Error).message,
      });
    }
  }
  const usable = out.filter((e) => e.segments.length > 0);
  if (!usable.length) return null;
  const aligned = usable.some((e) => e.segments.length === expected);
  return {
    provider: "suttacentral",
    upstream: work.upstream,
    upstreamRef: uid,
    upstreamUrl: `https://suttacentral.net/${uid}/en/${translator}`,
    fetchedAt: new Date().toISOString(),
    editions: out,
    aligned,
    cached: false,
    notice: aligned ? "" : `The hosted source divides this text into ${usable[0].segments.length} segments.`,
  };
}

