// ---------------------------------------------------------------------------
// SuttaCentral vagga ranges (Dhammapada)
// ---------------------------------------------------------------------------

async function fetchDhammapada(
  work: StreamWork,
  chapter: { ref: string; label: string; labels?: string[] },
  expected: number,
): Promise<StreamedChapter | null> {
  const ranges: string[] = work.config?.ranges ?? [];
  const range = ranges[Number(chapter.ref) - 1];
  if (!range) return null;
  const out: StreamedEdition[] = [];
  for (const edition of work.editions) {
    const isRoot = edition.language === "pi";
    const url = `https://suttacentral.net/api/bilarasuttas/${encodeURIComponent(range)}/sujato?lang=${isRoot ? "pi" : "en"}`;
    try {
      const { body } = await fetchJson(url, { timeoutMs: 30_000 });
      const text = (isRoot ? body?.root_text : body?.translation_text) ?? {};
      const keys: string[] = Array.isArray(body?.keys_order) ? body.keys_order : Object.keys(text);
      const byVerse = new Map<number, string[]>();
      for (const key of keys) {
        const match = /^dhp(\d+):(.+)$/.exec(key);
        if (!match) continue;
        // Segment 0.x is the chapter heading.
        if (/^0\./.test(match[2])) continue;
        const verse = Number(match[1]);
        if (!byVerse.has(verse)) byVerse.set(verse, []);
        const value = stripMarkup(String(text[key] ?? ""));
        if (value) byVerse.get(verse)!.push(value);
      }
      const segments = [...byVerse.entries()]
        .sort((a, b) => a[0] - b[0])
        .map(([, parts]) => parts.join(" "));
      out.push({
        slug: edition.slug,
        segments,
        versionTitle: edition.version,
        versionTitleHebrew: "",
        language: edition.language,
        license: edition.license,
        sourceUrl: "https://suttacentral.net/",
        pinned: true,
        error: segments.length ? undefined : `SuttaCentral returned no ${edition.language} verses`,
      });
    } catch (err) {
      out.push({
        slug: edition.slug,
        segments: [],
        versionTitle: edition.version,
        versionTitleHebrew: "",
        language: edition.language,
        license: edition.license,
        sourceUrl: "https://suttacentral.net/",
        pinned: true,
        error: (err as Error).message,
      });
    }
  }
  const usable = out.filter((e) => e.segments.length > 0);
  if (!usable.length) return null;
  const aligned = usable.some((e) => e.segments.length === expected);
  return {
    provider: "suttacentral",
    upstream: work.upstream,
    upstreamRef: range,
    upstreamUrl: `https://suttacentral.net/${range}/en/sujato`,
    fetchedAt: new Date().toISOString(),
    editions: out,
    aligned,
    cached: false,
    notice: aligned ? "" : `The hosted source returned ${usable[0].segments.length} verses for this chapter.`,
  };
}

// ---------------------------------------------------------------------------
// GRETIL plain-text transformations
// ---------------------------------------------------------------------------
//
// GRETIL publishes each Sanskrit text as one static plain-text file: a
// TEI-derived header block, then the text, in which every unit ends with the
// work's own reference — "// bhp_01.01.004 //", "SK_1", "| kvs_1,1.1 |". The
// file is therefore split by scanning for that abbreviation rather than by
// line or page, and a reference that belongs to another file (an editor's
// cross-reference, a page marker such as "BhGR_p9424") is not a cut.

export type GretilUnit = { ref: string; text: string };

/** Drop the TEI-derived header block GRETIL prints above the text. */
export function stripGretilHeader(raw: string): string {
  const text = raw.replace(/\r\n/g, "\n");
  const at = text.indexOf("\n# Text");
  return at >= 0 ? text.slice(at + "\n# Text".length).replace(/^\s+/, "") : text;
}

/** The leading lines of a file that are furniture (title, table of contents). */
function dropGretilLeadLines(body: string, count: number): string {
  if (!count) return body;
  const kept: string[] = [];
  let dropped = 0;
  for (const line of body.split("\n")) {
    if (dropped < count) {
      if (line.trim()) dropped++;
      continue;
    }
    kept.push(line);
  }
  return kept.join("\n");
}

/**
 * How one file numbers its units, where the abbreviation GRETIL prints is not
 * enough on its own.
 *
 * `refPattern` is the regular expression whose first group is the unit's own
 * number, for the files that carry no abbreviation at all and print the number
 * into the text instead (Spandakārikā's "|| 1 ||", Vivekacūḍāmaṇi's "// 1 //").
 * `trimDecorations` removes the apparatus some files print beside the marker —
 * a second reference in brackets (Gautama's "GautSt_1.1 [= GautAA_1.1.1]"), the
 * marker wrapped in underscores (the Mahāvastu's "[_mvu_1.1_]"), a word split
 * at the marker (the Udānavarga's "siddham(Uv_1.0)") — from the ends of every
 * unit, so no apparatus is shown as text.
 */
export type GretilReadOptions = { refPattern?: string; trimDecorations?: boolean };

/** One unit per reference: the text that precedes it, as one line. */
export function parseGretilUnits(
  body: string,
  abbrev: string,
  skipLeadLines = 0,
  options: GretilReadOptions = {},
): GretilUnit[] {
  const source = dropGretilLeadLines(body, skipLeadLines);
  // A file may number its parts in front of the chapter (the Nāradasmṛti
  // prints "NarS_m1.1" and "NarS_v3.4") and may give two chapters one joint
  // reference (its chapters on verbal and physical assault are numbered
  // "NarS_v15-16.1"), so one letter and one range are kept before the verse.
  const pattern = options.refPattern
    ? new RegExp(options.refPattern, "g")
    : new RegExp(
        `(?<![A-Za-z0-9])${abbrev.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}_([A-Za-z]?[0-9]+(?:-[0-9]+)?(?:[.,][0-9]+)*)`,
        "g",
      );
  const marks: { ref: string; from: number; to: number }[] = [];
  for (const match of source.matchAll(pattern)) {
    marks.push({ ref: match[1]!.replace(/,/g, "."), from: match.index!, to: match.index! + match[0].length });
  }
  const units: GretilUnit[] = [];
  let cursor = 0;
  for (const mark of marks) {
    const raw = source.slice(cursor, mark.from).replace(/\s+/g, " ").trim();
    cursor = mark.to;
    const trimmed = options.trimDecorations ? trimGretilDecorations(raw) : raw;
    const text = stripGretilMarks(trimmed);
    if (!text) continue;
    units.push({ ref: mark.ref, text });
  }
  return units;
}

/**
 * The marks the plain-text transformation leaves in the text, which are the
 * printed edition's furniture rather than words: the verse delimiters a file
 * wraps round a unit ("// … //", "| … |"), the number the editor prints in
 * front of it ("*1 …", "*1ab/ …"), the conversion's own file token
 * (",mang_cd/"), the rules that divide a text ("____", "******") and the
 * separators some files put between the parts of a verse ("$", "%", "&",
 * "@"). A delimiter inside a unit is left alone — the Mahāvastu prints "//"
 * between verses within one section — so only the ends are cut.
 */
export function stripGretilMarks(text: string): string {
  return text
    .replace(/,[A-Za-z][A-Za-z0-9_]*_cd\//g, " ")
    .replace(/^\s*[|/]+\s*/, "")
    .replace(/\s*[|/]+\s*$/, "")
    .replace(/^\s*\*\s?\d+[A-Za-z]*\s*\/?\s*/, "")
    .replace(/\*{2,}/g, " ")
    .replace(/_{3,}/g, " ")
    .replace(/(^|\s)[$%&@](?=\s|$)/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

/**
 * The e-text's own apparatus, taken off both ends of a unit. What is removed is
 * what the marker left behind: a crossing reference in brackets
 * ("GautSt_1.1 [= GautAA_1.1.1]"), the closer of a marker the file wrapped in
 * parentheses, and the opener of the marker still to come — never a parenthesis
 * the edition means to print, so the Kauṣītaki Brāhmaṇa's ritual labels in
 * "(agnyādhāna)" are left whole.
 */
function trimGretilDecorations(text: string): string {
  return text
    .replace(/\[=[^\]]*\]/g, " ")
    .replace(/^[\s_]*[\]\)]+[\s_]*/, "")
    .replace(/[\s_]*[\[\(]+[\s_]*$/, "")
    .replace(/^[\s_]+/, "")
    .replace(/[\s_]+$/, "")
    .replace(/\s+/g, " ")
    .trim();
}

/** The components of a GRETIL reference, with leading zeros removed. */
export function gretilComponents(ref: string): string[] {
  return ref.split(".").map((part) => part.replace(/^0+(?=\d)/, ""));
}

/** A unit belongs to the chapter named by everything but its last component. */
export function gretilChapterRef(ref: string): string {
  const parts = gretilComponents(ref);
  return parts.length > 1 ? parts.slice(0, -1).join(".") : "1";
}

async function fetchGretil(
  work: StreamWork,
  chapter: { ref: string; label: string },
  expected: number,
): Promise<StreamedChapter | null> {
  const config = work.config as {
    textUrl?: string;
    sourceUrl?: string;
    abbreviation?: string;
    skipLeadLines?: number;
    /**
     * How many components a passage reference of this work carries. Some files
     * mark chapter headings and colophons as well as passages, and a few
     * truncate a verse marker to the chapter number; the importer records the
     * depth a passage has, and the reader keeps only those references so the
     * page holds the same units the passage index was built from.
     */
    unitDepth?: number;
    /** The number pattern of a file that prints no abbreviation beside its references. */
    refPattern?: string;
    /** Whether the e-text's own apparatus is trimmed off the ends of each unit. */
    trimDecorations?: boolean;
    /**
     * A few GRETIL files interleave a root text with a commentary and mark each
     * with its own abbreviation (BrhUp for the mula, BrhUPBh for Samkara's
     * bhasya). An edition that names its own abbreviation is read from the same
     * file but indexed under its own marker, so the two stand side by side.
     */
    editions?: Record<string, { abbreviation?: string }>;
  };
  if (!config.textUrl || !(config.abbreviation || config.refPattern)) return null;
  let body = "";
  let error: string | undefined;
  try {
    body = await gutenbergText(config.textUrl);
  } catch (err) {
    error = (err as Error).message;
  }
  const bodyText = body ? stripGretilHeader(body) : "";
  const parsed = new Map<string, GretilUnit[]>();
  const unitsFor = (abbreviation: string) => {
    const hit = parsed.get(abbreviation);
    if (hit) return hit;
    const read = bodyText
      ? parseGretilUnits(bodyText, abbreviation, config.skipLeadLines ?? 0, {
          refPattern: config.refPattern,
          trimDecorations: config.trimDecorations,
        })
      : [];
    // Only the references this work numbers as passages are shown, so a chapter
    // heading the file marks like a verse is neither counted nor displayed.
    const units =
      config.unitDepth && read.length
        ? read.filter((unit) => unit.ref.split(".").length === config.unitDepth)
        : read;
    parsed.set(abbreviation, units);
    return units;
  };
  const primary = unitsFor(config.abbreviation!);
  const segments = primary.filter((unit) => gretilChapterRef(unit.ref) === chapter.ref).map((unit) => unit.text);
  const sourceUrl = config.sourceUrl ?? config.textUrl;
  const out: StreamedEdition[] = work.editions.map((edition) => {
    const abbreviation = config.editions?.[edition.slug]?.abbreviation ?? config.abbreviation!;
    const own =
      abbreviation === config.abbreviation
        ? segments
        : unitsFor(abbreviation)
            .filter((unit) => gretilChapterRef(unit.ref) === chapter.ref)
            .map((unit) => unit.text);
    return {
      slug: edition.slug,
      segments: own,
      versionTitle: edition.version,
      versionTitleHebrew: "",
      language: edition.language,
      license: edition.license,
      sourceUrl,
      pinned: true,
      error: own.length ? undefined : error ?? "GRETIL returned no text for this chapter",
    };
  });
  if (!segments.length) return null;
  const aligned = segments.length === expected;
  return {
    provider: "gretil",
    upstream: work.upstream,
    upstreamRef: chapter.label,
    upstreamUrl: sourceUrl,
    fetchedAt: new Date().toISOString(),
    editions: out,
    aligned,
    cached: false,
    notice: aligned
      ? ""
      : `GRETIL now serves ${segments.length} units for this chapter where the library indexed ${expected}. The text is shown as received.`,
  };
}

// ---------------------------------------------------------------------------
// Bahá’í Reference Library
// ---------------------------------------------------------------------------
//
// The Reference Library serves each publication of the Bahá’í writings as a
// series of numbered reading views (/1, /2, /3 …) — the site's own pagination,
// not a division of the text. Inside a view the library marks up the
// publication it prints: an element whose class names it as a heading carries
// the part or section title, a numbered paragraph carries the number the
// library prints in a brl-pnum anchor, and an unnumbered paragraph carries
// none. The importer records which views each chapter spans and the paragraph
// range inside them, so the reader fetches exactly the views that chapter needs
// and shows the paragraphs the passage index was built from.

export type BahaiBlock = { heading: string; number: string; text: string; anchor: string };

/** The headings and paragraphs of one reading view, in document order. */
export function bahaiBlocks(html: string): BahaiBlock[] {
  const marker = html.indexOf('class="library-document-content');
  if (marker < 0) return [];
  const start = html.lastIndexOf("<div", marker);
  const end = html.indexOf('class="loadmorecontent bottom', start);
  const region = html.slice(start, end > start ? end : html.length);
  const blocks: BahaiBlock[] = [];
  for (const match of region.matchAll(/<(h[1-6]|p)\b([^>]*)>([\s\S]*?)<\/\1>/gi)) {
    const attrs = match[2] ?? "";
    // A footnote marker is a superscript number the library links to its own
    // notes; the notes are the publication's apparatus and are not imported, so
    // the marker is dropped rather than left in the text or in a heading.
    const inner = (match[3] ?? "").replace(/<sup[^>]*class="[^"]*brl-note[^"]*"[^>]*>[\s\S]*?<\/sup>/gi, " ");
    // The library prints each numbered paragraph twice: once as a marginal
    // number of its own and once with the text. The marginal copy is a bare
    // "12." and is dropped here; in the copy that carries the text the same
    // number sits in an anchor of its own, and it is removed because the
    // passage reference already carries it.
    const numbered = inner.match(/<a[^>]*class="[^"]*brl-pnum[^"]*"[^>]*>\s*(\d+)\s*<\/a>/i);
    const text = stripMarkup(numbered ? inner.replace(numbered[0], " ") : inner);
    if (/class="[^"]*brl-head/i.test(attrs)) {
      if (text) blocks.push({ heading: text, number: "", text: "", anchor: /\bid="([^"]+)"/.exec(attrs)?.[1] ?? "" });
      continue;
    }
    if (!text || /^\d+\.$/.test(text) || NOISE.test(text)) continue;
    blocks.push({ heading: "", number: numbered?.[1] ?? "", text, anchor: /\bid="([^"]+)"/.exec(attrs)?.[1] ?? "" });
  }
  return blocks;
}

// ---------------------------------------------------------------------------
//
// The Chinese Text Project serves one reading page per chapter, in traditional
// characters, with the Chinese paragraphs in `td.ctext` cells and the site's own
// English in `td.etext` cells beside them. Only the Chinese text is imported:
// the pre-modern text is out of copyright, while the project's transcriptions,
// punctuation and translations are its own work and are credited, not copied.
//
// A book's page lists its chapters as links to `<book>/<chapter>/zh`, and a big
// book may nest one level further (a 卷 whose page lists its own sections), so a
// chapter is stored as the pages that hold it plus its paragraph range.

export type CtextChapterLink = { path: string; title: string; english: string };

/** The address of one ctext reading page, in traditional characters. */
export function ctextUrl(book: string, page = ""): string {
  return `https://ctext.org/${book}${page ? `/${page}` : ""}/zh`;
}

/** The Chinese paragraphs of one ctext reading page, in document order. */
export function ctextParagraphs(html: string): string[] {
  const out: string[] = [];
  for (const match of html.matchAll(/<td[^>]*class="(ctext[^"]*)"[^>]*>([\s\S]*?)<\/td>/g)) {
    // `ctext opt` is the running head the site prints beside each paragraph (the
    // chapter's own name); it is not a paragraph of the text.
    if (/\bopt\b/.test(match[1] ?? "")) continue;
    const inner = (match[2] ?? "")
      .replace(/<div[^>]*id="comm\d+"[^>]*>\s*<\/div>/gi, " ")
      .replace(/<div[^>]*class="[^"]*(?:commentary|note)[^"]*"[^>]*>[\s\S]*?<\/div>/gi, " ");
    const text = stripMarkup(inner);
    if (!text || NOISE.test(text)) continue;
    out.push(text);
  }
  return out;
}

/** The chapters a ctext book page lists, in printed order. */
export function ctextChapters(html: string, book: string): CtextChapterLink[] {
  const seen = new Set<string>();
  const out: CtextChapterLink[] = [];
  for (const match of html.matchAll(/<a[^>]*href="([^"]+?)\/zh"[^>]*>([\s\S]*?)<\/a>/g)) {
    const path = (match[1] ?? "")
      .replace(/^https?:\/\/ctext\.org\//, "")
      .replace(/^\/+/, "");
    if (!path.startsWith(`${book}/`)) continue;
    const relative = path.slice(book.length + 1);
    if (!relative || seen.has(relative)) continue;
    const label = match[2] ?? "";
    const english = /<span class="translationtitle">([\s\S]*?)<\/span>/i.exec(label)?.[1] ?? "";
    const title = stripMarkup(label.replace(/<span class="translationtitle">[\s\S]*?<\/span>/gi, ""));
    if (!title) continue;
    seen.add(relative);
    out.push({ path: relative, title, english: stripMarkup(english) });
  }
  return out;
}

type CtextConfig = {
  /** The book's path on ctext.org, e.g. "analects". */
  book: string;
  /** Per chapter: the pages that carry it and its paragraph range inside them. */
  chapters: Record<string, { label: string; pages: string[]; from: number; to: number }>;
  sourceUrl?: string;
};

/**
 * The paragraphs the import validated for one chapter, read back from the
 * library's own cache. The Chinese Text Project refuses whole networks — it
 * forbids automated downloading and blocks addresses it sees crawling — so a
 * work that was imported and indexed would otherwise have nothing to show. The
 * cache is a reader of last resort, never the first choice.
 */
function ctextCachedChapter(slug: string, ref: string): string[] | null {
  try {
    const cache = JSON.parse(
      readFileSync(join(ROOT, "data", "imports", "cache", "ctext", `${slug}.json`), "utf8"),
    ) as { chapters?: { ref: string; segments?: string[] }[] };
    const chapter = (cache.chapters ?? []).find((entry) => String(entry.ref) === String(ref));
    return chapter?.segments?.length ? chapter.segments.map(String) : null;
  } catch {
    return null;
  }
}

async function fetchCtext(
  work: StreamWork,
  chapter: { ref: string; label: string },
  expected: number,
): Promise<StreamedChapter | null> {
  const config = work.config as CtextConfig;
  const section = config.chapters?.[chapter.ref];
  if (!section) return null;
  const paragraphs: string[] = [];
  let error: string | undefined;
  for (const page of section.pages) {
    try {
      const html = await fetchHtmlText(ctextUrl(config.book, page));
      paragraphs.push(...ctextParagraphs(html));
    } catch (err) {
      error = (err as Error).message;
    }
  }
  let segments = paragraphs.slice(section.from, section.to + 1);
  let fromCache = false;
  if (!segments.length) {
    const cached = ctextCachedChapter(work.slug, chapter.ref);
    if (cached) {
      segments = cached;
      fromCache = true;
    }
  }
  if (!segments.length) return null;
  const sourceUrl = ctextUrl(config.book, section.pages[0] ?? "");
  const out: StreamedEdition[] = work.editions.map((edition) => ({
    slug: edition.slug,
    segments,
    versionTitle: edition.version,
    versionTitleHebrew: "",
    language: edition.language,
    license: edition.license,
    sourceUrl,
    pinned: true,
    error: segments.length ? undefined : error ?? "The Chinese Text Project returned no text for this chapter",
  }));
  const aligned = segments.length === expected;
  return {
    provider: "ctext",
    upstream: work.upstream,
    upstreamRef: section.label || chapter.label,
    upstreamUrl: sourceUrl,
    fetchedAt: new Date().toISOString(),
    editions: out,
    aligned,
    cached: fromCache,
    notice: fromCache
      ? "ctext.org could not be read from this network, so the chapter is shown from the transcription validated " +
        "at import time and held in the library's own cache. The Chinese Text Project is credited as its source."
      : aligned
        ? "Chinese text streamed from the Chinese Text Project; its transcription and punctuation are credited to ctext.org."
        : `The Chinese Text Project served ${segments.length} paragraph(s) for this chapter, where the index holds ${expected}. The text shown is the chapters the project serves today.`,
  };
}

