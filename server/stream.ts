// Wikisource
// ---------------------------------------------------------------------------

export function extractWikisourceSegments(
  html: string,
  options: { splitBreaks?: boolean } = {},
): string[] {
  const start = html.indexOf("mw-parser-output");
  let body = start >= 0 ? html.slice(start) : html;
  body = body.replace(/<style[\s\S]*?<\/style>/gi, " ");
  body = body.replace(/<script[\s\S]*?<\/script>/gi, " ");
  body = body.replace(/<!--[\s\S]*?-->/g, " ");
  // Wikisource's header, navigation and licence blocks are page furniture.
  body = body.replace(/<div class="ws-noexport"[\s\S]*?<\/div>/gi, " ");
  body = body.replace(/<table[\s\S]*?<\/table>/gi, " ");
  body = body.replace(/<div class="ws-summary"[\s\S]*?<\/div>/gi, " ");
  body = body.replace(/<span class="ws-poem-break"[^>]*>[\s\S]*?<\/span>/gi, " ");
  const blocks: { index: number; text: string }[] = [];
  const numbered = new Set<number>();
  // Wikisource prints poetry as spans, one line each, with the verse number in
  // a sibling span. Keeping each line is what lets a poem be quoted by line
  // rather than swallowed into one paragraph.
  for (const match of body.matchAll(
    /<span class="ws-poem-versenum">([\s\S]*?)<\/span>\s*<span class="ws-poem-line">([\s\S]*?)<\/span>/gi,
  )) {
    const number = stripMarkup(match[1]);
    const line = stripMarkup(match[2]);
    if (line) blocks.push({ index: match.index ?? 0, text: `${number} ${line}`.trim() });
    numbered.add((match.index ?? 0) + match[0].indexOf('<span class="ws-poem-line">'));
  }
  for (const match of body.matchAll(/<span class="ws-poem-line">([\s\S]*?)<\/span>/gi)) {
    if (numbered.has(match.index ?? -1)) continue;
    const text = stripMarkup(match[1]);
    if (text) blocks.push({ index: match.index ?? 0, text });
  }
  // Some verse pages use a <pre> block rather than poem spans. Keep one
  // segment per printed line so the verse can still be cited by line.
  for (const match of body.matchAll(/<pre\b[^>]*>([\s\S]*?)<\/pre>/gi)) {
    const inner = match[1] ?? "";
    const base = match.index ?? 0;
    let offset = 0;
    for (const line of inner.split(/\r?\n/)) {
      const text = stripMarkup(line);
      if (text.length > 1) blocks.push({ index: base + offset, text });
      offset += line.length + 1;
    }
  }
  for (const match of body.matchAll(/<p\b[^>]*>([\s\S]*?)<\/p>/gi)) {
    // Some transcriptions set a whole poem as one paragraph with a <br> at the
    // end of every line. Where the work asks for it, keep each line as its own
    // segment so a verse can be quoted by line rather than by stanza.
    if (options.splitBreaks && /<br\s*\/?>/i.test(match[1])) {
      let offset = 0;
      for (const line of match[1].split(/<br\s*\/?>/i)) {
        const text = stripMarkup(line);
        if (text.length > 1) blocks.push({ index: (match.index ?? 0) + offset, text });
        offset += line.length + 4;
      }
      continue;
    }
    const text = stripMarkup(match[1]);
    if (text.length > 1) blocks.push({ index: match.index ?? 0, text });
  }
  return blocks
    .sort((a, b) => a.index - b.index)
    .map((block) => block.text.replace(/\s+/g, " ").trim())
    .filter(
      (text) =>
        text.length > 1 &&
        !/^\d+$/.test(text) &&
        // Running heads, the work title repeated at the top of a page, and the
        // pagenum placeholder are furniture, not text.
        !/^(?:page|contents|index)$/i.test(text) &&
        !/^layout \d+$/i.test(text) &&
        !/^Khandas \(not listed in original\)$/i.test(text) &&
        !/^[^a-z]{1,80}$/.test(text) &&
        // Wikisource prints untranscribed Arabic script as an image with alt text.
        !/^\((?:Arabic|Persian|Hebrew|Aramaic) characters?\)$/i.test(text),
    );
}

async function fetchWikisource(
  work: StreamWork,
  chapter: { ref: string; label: string },
  expected: number,
): Promise<StreamedChapter | null> {
  const pages: { title: string; url: string; ref?: string }[] = work.config?.pages ?? [];
  // Most Wikisource works number their pages 1..n, so the chapter ref selects
  // the page directly. A work whose refs follow its own scheme (the Rigveda is
  // book.hymn) records the ref on the page; older configs can still be matched
  // by the chapter label, which is the page title's trailing path.
  const page =
    pages.find((entry) => entry.ref === chapter.ref) ??
    (/^\d+$/.test(chapter.ref) ? pages[Number(chapter.ref) - 1] : undefined) ??
    pages.find((entry) => entry.title.endsWith(`/${chapter.label.replace(/,\s*/g, "/")}`));
  if (!page) return null;
  const out: StreamedEdition[] = [];
  let segments: string[] = [];
  let error: string | undefined;
  try {
    const { body } = await fetchJson(
      `https://en.wikisource.org/w/api.php?action=parse&page=${encodeURIComponent(page.title)}&prop=text&format=json&formatversion=2`,
      { timeoutMs: 30_000 },
    );
    segments = extractWikisourceSegments(String(body?.parse?.text ?? ""), {
      splitBreaks: Boolean(work.config?.splitBreaks),
    });
    // Some transcriptions print a translation credit or a table of contents
    // above the work. The pattern is stored with the work so the import and
    // the reader drop exactly the same leading blocks.
    const trim = work.config?.trimStartPattern
      ? new RegExp(String(work.config.trimStartPattern), "i")
      : null;
    while (trim && segments.length && trim.test(segments[0]!)) segments.shift();
  } catch (err) {
    error = (err as Error).message;
  }
  for (const edition of work.editions) {
    out.push({
      slug: edition.slug,
      segments,
      versionTitle: edition.version,
      versionTitleHebrew: "",
      language: edition.language,
      license: edition.license,
      sourceUrl: page.url,
      pinned: true,
      error: segments.length ? undefined : error ?? "The Wikisource page returned no text",
    });
  }
  const usable = out.filter((e) => e.segments.length > 0);
  if (!usable.length) return null;
  const aligned = usable.some((e) => e.segments.length === expected);
  return {
    provider: "wikisource",
    upstream: work.upstream,
    upstreamRef: page.title,
    upstreamUrl: page.url,
    fetchedAt: new Date().toISOString(),
    editions: out,
    aligned,
    cached: false,
    notice: aligned
      ? ""
      : `The Wikisource page now yields ${usable[0].segments.length} paragraphs where the library indexed ${expected}. The text is shown as received.`,
  };
}

// ---------------------------------------------------------------------------
// Project Gutenberg plain text
// ---------------------------------------------------------------------------
//
// Some public-domain translations exist only as a single text file. Each
// chapter begins at a heading line, and the same split runs at import and at
// read time, so the passage index and the served text cannot diverge silently.

export type PlaintextAnchor = {
  ref: string;
  marker: string;
  occurrence?: "first" | "last";
  /** Zero-based choice among identical heading lines, for repeated headings. */
  occurrenceIndex?: number;
  /** Drop leading lines of a section that match this pattern before splitting. */
  trimStartPattern?: string;
};

function cleanPlaintext(text: string): string {
  return text.replace(/\r\n/g, "\n").replace(/[\u00a0]/g, " ");
}

export function plaintextParagraphs(body: string): string[] {
  const out: string[] = [];
  for (const raw of cleanPlaintext(body).split(/\n\s*\n/)) {
    let text = raw
      .split("\n")
      .map((line) => line.trim())
      .filter(Boolean)
      .join(" ")
      .replace(/\s+/g, " ")
      .trim();
    // Gutenberg marks emphasis with =…= and _…_; the marks are not the text.
    if (text.length > 2 && text.startsWith("=") && text.endsWith("=")) text = text.slice(1, -1).trim();
    text = text.replace(/(^|[\s(“"'])_([^_]{1,240})_(?=[\s.,;:!?”"')]|$)/g, "$1$2");
    if (text.length < 2) continue;
    if (/^\[?\d+\]?$/.test(text)) continue;
    if (/^(FOOTNOTES|TRANSCRIBER|THE END|IT IS ENDED|START OF THE PROJECT|END OF THE PROJECT)/i.test(text)) continue;
    out.push(text);
  }
  return out;
}

/**
 * Keep one line per segment. Used for verse editions, where a stanza is written
 * as single lines and joining them into a paragraph would destroy the metre.
 */
export function plaintextLines(body: string): string[] {
  const out: string[] = [];
  for (const raw of cleanPlaintext(body).split("\n")) {
    let text = raw.trim().replace(/\s+/g, " ");
    if (text.length < 2) continue;
    if (/^\[?\d+\]?$/.test(text)) continue;
    if (/^(FOOTNOTES|TRANSCRIBER|THE END|IT IS ENDED|START OF THE PROJECT|END OF THE PROJECT|\*\*\* END)/i.test(text)) continue;
    // Gutenberg marks emphasis with =…= and _…_; the marks are not the text.
    if (text.length > 2 && text.startsWith("=") && text.endsWith("=")) text = text.slice(1, -1).trim();
    text = text.replace(/(^|[\s(“"'])_([^_]{1,240})_(?=[\s.,;:!?”"')]|$)/g, "$1$2");
    if (text.length < 2) continue;
    out.push(text);
  }
  return out;
}

/**
 * Some plain-text editions print a whole chapter as running prose with hard
 * line breaks inside one block, so the paragraph splitter yields a single wall
 * of text. Repacking the sentences into reader-sized paragraphs changes no
 * words; the import and the reader run the same packing, so the passage index
 * stays aligned with the served text.
 */
export function packSentences(text: string, maxWords: number): string[] {
  const sentences = text
    .replace(/\s+/g, " ")
    .trim()
    .split(/(?<=[.!?]["'’”]?)\s+/);
  const out: string[] = [];
  let current: string[] = [];
  let words = 0;
  for (const sentence of sentences) {
    if (!sentence) continue;
    const count = sentence.split(" ").filter(Boolean).length;
    if (current.length && words + count > maxWords) {
      out.push(current.join(" "));
      current = [];
      words = 0;
    }
    current.push(sentence);
    words += count;
  }
  if (current.length) out.push(current.join(" "));
  return out;
}

/** The Gutenberg licence block is not part of the work it follows. */
function trimGutenberg(text: string, marker = "*** END OF THE PROJECT GUTENBERG"): string {
  const index = text.indexOf(marker);
  return index > 0 ? text.slice(0, index) : text;
}

/** Split one plain-text edition into the chapters named by its anchors. */
export function splitPlaintextChapters(text: string, anchors: PlaintextAnchor[]): Map<string, string> {
  const source = cleanPlaintext(trimGutenberg(text));
  const found: { ref: string; start: number; index: number }[] = [];
  for (const anchor of anchors) {
    const escaped = anchor.marker.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    // The heading must be a line of its own: a table-of-contents line carries a
    // page number after the same words and must not start a chapter.
    const pattern = new RegExp(`(?:^|\\n)[ \\t]*${escaped}[ \\t]*\\r?\\n`, "g");
    const hits = [...source.matchAll(pattern)];
    const hit =
      anchor.occurrenceIndex != null
        ? hits[anchor.occurrenceIndex]
        : anchor.occurrence === "last"
          ? hits[hits.length - 1]
          : hits[0];
    if (!hit || hit.index === undefined) continue;
    found.push({ ref: anchor.ref, index: hit.index, start: hit.index + hit[0].length });
  }
  found.sort((a, b) => a.index - b.index);
  const out = new Map<string, string>();
  for (const [i, entry] of found.entries()) {
    const start = entry.start;
    const end = i + 1 < found.length ? found[i + 1]!.index : source.length;
    let body = source.slice(start, end);
    // Footnotes and the licence block are at the end of a section, not part of it.
    const footnote = body.search(/\n\s*(FOOTNOTES?:?\s*\n|\*\*\* END OF)/);
    if (footnote > 0) body = body.slice(0, footnote);
    out.set(entry.ref, body);
  }
  return out;
}

type GutenbergVolume = { textUrl: string; sourceUrl?: string; anchors: PlaintextAnchor[] };

// A multi-volume prose work is split at headings in each volume. Fetching a
// 3 MB volume again for every one of its sections would make the reader crawl,
// so the served text is kept briefly in memory.
const GUTENBERG_TTL = 30 * 60 * 1000;
const GUTENBERG_MAX = 6;
const gutenbergCache = new Map<string, { at: number; text: string }>();

async function gutenbergText(url: string): Promise<string> {
  const hit = gutenbergCache.get(url);
  if (hit && Date.now() - hit.at < GUTENBERG_TTL) return hit.text;
  let last: Error | null = null;
  for (let attempt = 1; attempt <= 3; attempt++) {
    try {
      const res = await fetch(url, {
        headers: {
          accept: "text/plain",
          "user-agent": "UniversalWisdomLibrary/1.0 (local reading interface; streamed text)",
        },
        signal: AbortSignal.timeout(90_000),
      });
      if (res.status === 429 || res.status >= 500) {
        last = new Error(`${url} returned ${res.status}`);
        await Bun.sleep(600 * attempt * attempt);
        continue;
      }
      if (!res.ok) throw new Error(`${url} returned ${res.status}`);
      const text = await res.text();
      if (gutenbergCache.size >= GUTENBERG_MAX) {
        const oldest = [...gutenbergCache.entries()].sort((a, b) => a[1].at - b[1].at)[0];
        if (oldest) gutenbergCache.delete(oldest[0]);
      }
      gutenbergCache.set(url, { at: Date.now(), text });
      return text;
    } catch (err) {
      last = err as Error;
      if (attempt < 3) await Bun.sleep(400 * attempt);
    }
  }
  throw last ?? new Error(`${url} failed`);
}

async function fetchGutenberg(
  work: StreamWork,
  chapter: { ref: string; label: string },
  expected: number,
): Promise<StreamedChapter | null> {
  const config = work.config as {
    textUrl?: string;
    anchors?: PlaintextAnchor[];
    sourceUrl?: string;
    volumes?: GutenbergVolume[];
    poem?: boolean;
    /** Repack unbroken prose into paragraphs of at most this many words. */
    paragraphWords?: number;
    endMarker?: string;
  };
  const volumes: GutenbergVolume[] = config.volumes?.length
    ? config.volumes
    : config.textUrl && config.anchors?.length
      ? [{ textUrl: config.textUrl, sourceUrl: config.sourceUrl, anchors: config.anchors }]
      : [];
  if (!volumes.length) return null;
  const volume =
    volumes.find((candidate) => candidate.anchors.some((anchor) => anchor.ref === chapter.ref)) ??
    (volumes.length === 1 ? volumes[0] : null);
  if (!volume) return null;

  let body = "";
  let error: string | undefined;
  try {
    body = await gutenbergText(volume.textUrl);
  } catch (err) {
    error = (err as Error).message;
  }
  const chapters = body
    ? splitPlaintextChapters(trimGutenberg(body, config.endMarker), volume.anchors)
    : new Map<string, string>();
  let section = chapters.get(chapter.ref) ?? "";
  const anchor = volume.anchors.find((candidate) => candidate.ref === chapter.ref);
  if (section && anchor?.trimStartPattern) {
    const trim = new RegExp(anchor.trimStartPattern, "i");
    const lines = section.split(/\r?\n/);
    let start = 0;
    while (start < lines.length && (!lines[start]!.trim() || trim.test(lines[start]!.trim()))) start++;
    section = lines.slice(start).join("\n");
  }
  const segments = config.poem
    ? plaintextLines(section)
    : config.paragraphWords
      ? packSentences(plaintextParagraphs(section).join(" "), config.paragraphWords)
      : plaintextParagraphs(section);
  const sourceUrl = volume.sourceUrl ?? config.sourceUrl ?? volume.textUrl;
  const out: StreamedEdition[] = work.editions.map((edition) => ({
    slug: edition.slug,
    segments,
    versionTitle: edition.version,
    versionTitleHebrew: "",
    language: edition.language,
    license: edition.license,
    sourceUrl,
    pinned: true,
    error: segments.length ? undefined : error ?? "The hosted text returned no paragraphs for this chapter",
  }));
  if (!segments.length) return null;
  const aligned = segments.length === expected;
  return {
    provider: "gutenberg",
    upstream: work.upstream,
    upstreamRef: chapter.label,
    upstreamUrl: sourceUrl,
    fetchedAt: new Date().toISOString(),
    editions: out,
    aligned,
    cached: false,
    notice: aligned
      ? ""
      : `The hosted text now yields ${segments.length} paragraphs for this chapter where the library indexed ${expected}. The text is shown as received.`,
  };
}

// ---------------------------------------------------------------------------
// Internet Archive full-text
// ---------------------------------------------------------------------------
//
// A public-domain scan often exists only as the OCR text beside a page-image
// volume. The item's metadata names the server that holds the derivative, and
// the same chapter splitter used for Gutenberg keeps the reading index and the
// served text in step.

async function fetchArchive(
  work: StreamWork,
  chapter: { ref: string; label: string },
  expected: number,
): Promise<StreamedChapter | null> {
  const config = work.config as {
    item?: string;
    file?: string;
    textUrl?: string;
    anchors?: PlaintextAnchor[];
    sourceUrl?: string;
    poem?: boolean;
    endMarker?: string;
  };
  if (!config.anchors?.length) return null;
  let textUrl = config.textUrl ?? "";
  let body = "";
  let error: string | undefined;
  try {
    if (!textUrl && config.item) {
      const meta = await fetchJson(`https://archive.org/metadata/${encodeURIComponent(config.item)}`, {
        timeoutMs: 30_000,
      });
      const files: { name?: string }[] = Array.isArray(meta?.files) ? meta.files : [];
      const file =
        config.file ?? files.find((f) => typeof f.name === "string" && f.name.endsWith("_djvu.txt"))?.name;
      if (!file || !meta?.server || !meta?.dir) throw new Error("The item has no readable plain-text derivative");
      textUrl = `https://${meta.server}${meta.dir}/${encodeURIComponent(file)}`;
    }
    if (!textUrl) throw new Error("The archive item has no text address");
    const res = await fetch(textUrl, {
      headers: {
        accept: "text/plain",
        "user-agent": "UniversalWisdomLibrary/1.0 (local reading interface; streamed text)",
      },
      signal: AbortSignal.timeout(60_000),
    });
    if (!res.ok) throw new Error(`${textUrl} returned ${res.status}`);
    body = await res.text();
  } catch (err) {
    error = (err as Error).message;
  }
  const chapters = body
    ? splitPlaintextChapters(trimGutenberg(body, config.endMarker), config.anchors)
    : new Map<string, string>();
  const section = chapters.get(chapter.ref) ?? "";
  const segments = config.poem ? plaintextLines(section) : plaintextParagraphs(section);
  const out: StreamedEdition[] = work.editions.map((edition) => ({
    slug: edition.slug,
    segments,
    versionTitle: edition.version,
    versionTitleHebrew: "",
    language: edition.language,
    license: edition.license,
    sourceUrl: config.sourceUrl ?? (config.item ? `https://archive.org/details/${config.item}` : textUrl),
    pinned: true,
    error: segments.length ? undefined : error ?? "The archived text returned no lines for this chapter",
  }));
  if (!segments.length) return null;
  const aligned = segments.length === expected;
  return {
    provider: "archive",
    upstream: work.upstream,
    upstreamRef: chapter.label,
    upstreamUrl: config.sourceUrl ?? (config.item ? `https://archive.org/details/${config.item}` : textUrl),
    fetchedAt: new Date().toISOString(),
    editions: out,
    aligned,
    cached: false,
    notice: aligned
      ? ""
      : `The archived text now yields ${segments.length} lines for this chapter where the library indexed ${expected}. The text is shown as received.`,
  };
}

// ---------------------------------------------------------------------------
// OpenITI mARkdown
// ---------------------------------------------------------------------------
//
// One repository file holds a whole work. It is fetched once and both the raw
// mARkdown and the grouped chapters are kept for a reading session; fetching a
// 13 MB file again for every chapter would make a large manual unusable.

const OPENITI_TTL = 30 * 60 * 1000;
const OPENITI_MAX = 6;
const openitiCache = new Map<string, { at: number; chapters: OpenitiSection[] }>();

async function openitiText(work: StreamWork): Promise<OpenitiSection[]> {
  const url = String(work.config?.textUrl ?? "");
  const rule = work.config?.chapter;
  if (!url || !rule) throw new Error("The OpenITI work has no text address or chapter rule");

  const hit = openitiCache.get(url);
  if (hit && Date.now() - hit.at < OPENITI_TTL) return hit.chapters;

  let last: Error | null = null;
  for (let attempt = 1; attempt <= 3; attempt++) {
    try {
      const res = await fetch(url, {
        headers: {
          accept: "text/plain",
          "user-agent": "UniversalWisdomLibrary/1.0 (local reading interface; streamed text)",
        },
        signal: AbortSignal.timeout(180_000),
      });
      if (res.status === 429 || res.status >= 500) {
        last = new Error(`${url} returned ${res.status}`);
        await Bun.sleep(800 * attempt * attempt);
        continue;
      }
      if (!res.ok) throw new Error(`${url} returned ${res.status}`);
      const chapters = openitiChapters(parseOpeniti(await res.text()), rule);
      if (!chapters.length) throw new Error("The OpenITI file yielded no chapters");
      if (openitiCache.size >= OPENITI_MAX) {
        const oldest = [...openitiCache.entries()].sort((a, b) => a[1].at - b[1].at)[0];
        if (oldest) openitiCache.delete(oldest[0]);
      }
      openitiCache.set(url, { at: Date.now(), chapters });
      return chapters;
    } catch (err) {
      last = err as Error;
      if (attempt < 3) await Bun.sleep(600 * attempt);
    }
  }
  throw last ?? new Error(`${url} failed`);
}

