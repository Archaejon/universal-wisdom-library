const TTL = 10 * 60_000;
const MAX_ENTRIES = 240;
const memo = new Map<string, { at: number; value: StreamedChapter }>();
const inflight = new Map<string, Promise<StreamedChapter | null>>();

type ChapterRequest = { ref: string; label: string; labels?: string[] };
type ChapterFetcher = (
  work: StreamWork,
  chapter: ChapterRequest,
  expected: number,
) => Promise<StreamedChapter | null>;

/**
 * One fetcher per provider. A new source is one entry here and one entry in
 * `PROVIDER_LABEL`; the reader resolves a work's provider by name instead of
 * walking a chain of conditions that has to be read as a whole to be followed.
 */
const STREAM_FETCHERS: Record<string, ChapterFetcher> = {
  sefaria: fetchSefaria,
  suttacentral: (work, chapter, expected) =>
    work.config?.mode === "dhammapada"
      ? fetchDhammapada(work, chapter, expected)
      : fetchSuttaCentral(work, chapter, expected),
  "alquran-cloud": fetchAlQuran,
  "quran-tafsir": fetchQuranTafsir,
  bolls: fetchBolls,
  ccel: fetchHtmlWork,
  newadvent: fetchHtmlWork,
  "sacred-texts": fetchHtmlWork,
  hadith: fetchHadith,
  wikisource: fetchWikisource,
  gutenberg: fetchGutenberg,
  gretil: fetchGretil,
  archive: fetchArchive,
  openiti: fetchOpeniti,
  bahai: fetchBahai,
  "sacred-texts-json": fetchSacredTextsJson,
  ctext: fetchCtext,
  heritage: fetchHeritage,
};

export async function getStreamChapter(
  workSlug: string,
  chapter: ChapterRequest,
  expected: number,
): Promise<StreamedChapter | null> {
  const work = streamWork(workSlug);
  if (!work) return null;
  const key = `${workSlug}:${chapter.ref}`;
  const hit = memo.get(key);
  if (hit && Date.now() - hit.at < TTL) {
    return { ...hit.value, cached: true };
  }
  const running = inflight.get(key);
  if (running) {
    const value = await running;
    return value ? { ...value, cached: true } : null;
  }
  const task = (async () => {
    try {
      const fetcher = STREAM_FETCHERS[work.provider];
      const result = fetcher ? await fetcher(work, chapter, expected) : null;
      // A chapter that served nothing — an absent key, a refused one, a host
      // that did not answer — is returned as it is but not kept: setting the key
      // or waiting out an outage should be enough to read it, without waiting for
      // a cache entry that holds no text to expire.
      const empty = result?.editions.every((edition) => !edition.segments.some(Boolean));
      if (result && !empty) {
        if (memo.size >= MAX_ENTRIES) {
          const oldest = [...memo.entries()].sort((a, b) => a[1].at - b[1].at)[0];
          if (oldest) memo.delete(oldest[0]);
        }
        memo.set(key, { at: Date.now(), value: result });
      }
      return result;
    } catch (err) {
      console.error(`Stream fetch failed for ${key}:`, err);
      return null;
    } finally {
      inflight.delete(key);
    }
  })();
  inflight.set(key, task);
  return task;
}

export function clearStreamCache() {
  memo.clear();
}

// ---------------------------------------------------------------------------
// Search across streamed text
// ---------------------------------------------------------------------------
//
// The local index cannot cover text the library does not hold. Sefaria's search
// API is used instead, and a hit is only offered as a link when its reference
// exists in this library's passage index. Everything else stays on the host.

type SearchHit = {
  workSlug: string;
  workTitle: string;
  tradition: string;
  reference: string;
  label: string;
  snippet: string;
  editionTitle: string;
  language: string;
  upstreamRef: string;
};

const searchMemo = new Map<string, { at: number; value: StreamedSearch }>();
export type StreamedSearch = {
  provider: string;
  providerLabel: string;
  query: string;
  hits: SearchHit[];
  total: number;
  searchedAt: string;
  note: string;
  externalUrl: string;
};

function unversionedRef(text: string): string {
  // "Genesis 1:3 (The Holy Scriptures. A New Translation (JPS 1917) [en])"
  // carries a version note that can itself contain parentheses.
  return text.replace(/\s*\((?:[^()]|\([^()]*\))*\)\s*$/, "").trim();
}

function searchIndex() {
  const rows = getDb()
    .query(
      `SELECT ws.work_slug, ws.upstream_id, w.title, t.name AS tradition
       FROM work_streams ws JOIN works w ON w.slug = ws.work_slug
       JOIN traditions t ON t.id = w.tradition_id
       ORDER BY LENGTH(ws.upstream_id) DESC`,
    )
    .all() as Row[];
  return rows;
}

export async function searchStreamed(q: string, limit = 12): Promise<StreamedSearch | null> {
  const query = q.trim();
  if (query.length < 2) return null;
  const cached = searchMemo.get(query);
  if (cached && Date.now() - cached.at < 5 * 60_000) return { ...cached.value, hits: cached.value.hits.slice(0, limit) };
  let body: any;
  try {
    const result = await fetchJson("https://www.sefaria.org/api/search-wrapper", {
      method: "POST",
      headers: { "content-type": "application/json" },
      body: JSON.stringify({ query, type: "text", field: "naive_lemmatizer", size: 40, start: 0 }),
      timeoutMs: 20_000,
    });
    body = result.body;
  } catch (err) {
    console.error("Sefaria search failed:", err);
    return null;
  }
  const works = searchIndex();
  const db = getDb();
  const passageExists = db.query(
    "SELECT p.reference, p.label FROM passages p JOIN works w ON w.id = p.work_id WHERE w.slug = ? AND p.reference = ?",
  );
  const seen = new Set<string>();
  const hits: SearchHit[] = [];
  for (const hit of body?.hits?.hits ?? []) {
    const id = String(hit._id ?? "");
    const work = works.find((w) => id === w.upstream_id || id.startsWith(`${w.upstream_id} `));
    if (!work) continue;
    const rest = id.slice(work.upstream_id.length).trim();
    const upstreamRef = unversionedRef(rest);
    const reference = upstreamRef.replaceAll(":", ".").replace(/\s+/g, " ");
    const passage = passageExists.get(work.work_slug, reference) as Row | null;
    if (!passage) continue;
    const key = `${work.work_slug}:${reference}`;
    if (seen.has(key)) continue;
    seen.add(key);
    const highlight = hit.highlight?.naive_lemmatizer ?? [];
    const snippet = stripMarkup(String(highlight[0] ?? ""));
    const version = rest.slice(upstreamRef.length).replace(/^\s*\(/, "").replace(/\)\s*$/, "");
    hits.push({
      workSlug: work.work_slug,
      workTitle: work.title,
      tradition: work.tradition,
      reference,
      label: String(passage.label ?? reference),
      snippet,
      editionTitle: version.replace(/\s*\[[a-z]{2,3}\]\s*$/, "").trim(),
      language: /\[([a-z]{2,3})\]\s*\)?$/.exec(version)?.[1] ?? "he",
      upstreamRef,
    });
    if (hits.length >= 40) break;
  }
  const value: StreamedSearch = {
    provider: "sefaria",
    providerLabel: "Sefaria",
    query,
    hits,
    total: Number(body?.hits?.total?.value ?? body?.hits?.total ?? hits.length),
    searchedAt: new Date().toISOString(),
    note:
      "Streamed texts are searched on Sefaria's index. Only hits whose reference exists in this library are listed; the full result set opens at Sefaria.",
    externalUrl: `https://www.sefaria.org/search?q=${encodeURIComponent(query)}`,
  };
  if (searchMemo.size >= 60) searchMemo.clear();
  searchMemo.set(query, { at: Date.now(), value });
  return { ...value, hits: hits.slice(0, limit) };
}
