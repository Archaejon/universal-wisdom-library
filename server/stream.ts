export function stripMarkup(input: string): string {
  return String(input)
    .replace(/<br\s*\/?>/gi, " ")
    // Strong's numbers in the Bolls KJV are wrapped in <S>…</S>; the numbers
    // are a study aid, not part of the verse.
    .replace(/<S>\s*\d+\s*<\/S>/gi, "")
    .replace(/<[^>]*>/g, "")
    .replace(/&nbsp;/g, " ")
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&#39;|&apos;/g, "'")
    .replace(/&([a-zA-Z]+);/g, (entity, name) => NAMED_ENTITIES[name] ?? entity)
    .replace(/&#x([0-9a-f]+);/gi, (_, hex) => String.fromCodePoint(parseInt(hex, 16)))
    .replace(/&#(\d+);/g, (_, dec) => String.fromCodePoint(Number(dec)))
    .replace(/[\u200b-\u200f\u202a-\u202e]/g, "")
    .replace(/\s+/g, " ")
    .trim();
}

/** Sefaria returns a string, a list of strings, or a list of paragraph arrays. */
function flatten(value: any): string {
  if (typeof value === "string") return stripMarkup(value);
  if (Array.isArray(value)) return value.map(flatten).filter(Boolean).join(" ");
  return "";
}

export function toSegments(text: any): string[] {
  if (typeof text === "string") return [stripMarkup(text)].filter(Boolean);
  if (Array.isArray(text)) return text.map(flatten).filter((s) => s.length > 0);
  return [];
}

function leaves(value: any): string[] {
  if (typeof value === "string") return [stripMarkup(value)].filter(Boolean);
  if (Array.isArray(value)) return value.flatMap(leaves);
  return [];
}

// Complex Sefaria works sometimes return a chapter as a list of sub-sections,
// each holding its paragraphs. If splitting down to the leaves matches the
// local passage count, use that; otherwise keep the top-level segmentation.
export function segmentsFor(text: any, expected: number): string[] {
  const top = toSegments(text);
  if (!Array.isArray(text) || top.length === expected) return top;
  const deep = leaves(text);
  if (deep.length === expected) return deep;
  if (top.length === 0) return deep;
  return Math.abs(deep.length - expected) < Math.abs(top.length - expected) && deep.length > 0 ? deep : top;
}

async function fetchJson(
  url: string,
  init: RequestInit & { timeoutMs?: number; retryOn429?: boolean; retryOn5xx?: boolean } = {},
): Promise<any> {
  const { timeoutMs = 25_000, retryOn429 = true, retryOn5xx = true, ...rest } = init;
  let lastError: Error | null = null;
  for (let attempt = 1; attempt <= 3; attempt++) {
    try {
      const res = await fetch(url, {
        ...rest,
        headers: {
          accept: "application/json",
          "user-agent": "UniversalWisdomLibrary/1.0 (local reading interface; streamed text)",
          ...(rest.headers ?? {}),
        },
        signal: AbortSignal.timeout(timeoutMs),
      });
      if ((retryOn429 && res.status === 429) || (retryOn5xx && res.status >= 500)) {
        lastError = new Error(`${url} returned ${res.status}`);
        await Bun.sleep(400 * attempt * attempt);
        continue;
      }
      // The caller itself decides what a 429 means when retries are off; there is
      // no body to read and the status is the whole answer.
      if (res.status === 429) return { status: 429, body: null };
      // An error page is often HTML, and a parse error would replace the status
      // the caller can act on with "Unrecognized token '<'". Read the status and
      // only parse a body that claims to be JSON.
      const type = res.headers.get("content-type") ?? "";
      if (type.includes("json")) return { status: res.status, body: await res.json().catch(() => null) };
      if (!res.ok) return { status: res.status, body: null };
      return { status: res.status, body: await res.text() };
    } catch (err) {
      lastError = err as Error;
      if (attempt < 3) await Bun.sleep(300 * attempt);
    }
  }
  throw lastError ?? new Error(`${url} failed`);
}

