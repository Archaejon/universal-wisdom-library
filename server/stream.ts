async function fetchSacredTextsJson(
  work: StreamWork,
  chapter: { ref: string; label: string },
  expected: number,
): Promise<StreamedChapter | null> {
  const config = work.config as SacredTextsJsonConfig;
  const section = config.chapters?.[chapter.ref];
  if (!section) return null;
  const paragraphs: string[] = [];
  let error: string | undefined;
  for (const [index, slug] of section.pages.entries()) {
    const url = `${sacredTextsView(config, slug)}/__data.json`;
    // The archive's filter answers a burst with a challenge that lifts again; a
    // chapter of twelve views is a burst, so each view is asked for with a gap
    // and a refusal is waited out rather than reported as a short chapter.
    if (index) await Bun.sleep(400);
    try {
      let status = 0;
      let data: any = null;
      for (let attempt = 1; attempt <= 3; attempt++) {
        ({ status, data } = await sacredTextsJson(url));
        if (status === 200) break;
        if (status !== 403 && status !== 429 && status < 500) break;
        await Bun.sleep(1_200 * attempt);
      }
      if (status !== 200) {
        error = `${url} answered ${status}`;
        continue;
      }
      const html = String(svelteKitData(data)?.chapterContent?.contentHtml ?? "");
      if (!html) {
        error = `${url} carried no text`;
        continue;
      }
      paragraphs.push(...sacredTextsPage(html).segments);
    } catch (err) {
      error = (err as Error).message;
    }
  }
  let segments = paragraphs;
  let fromCache = false;
  if (!segments.length) {
    const cached = sacredTextsCachedChapter(work.slug, chapter.ref);
    if (cached) {
      segments = cached;
      fromCache = true;
    }
  }
  if (!segments.length) return null;
  const sourceUrl = sacredTextsView(config, section.pages[0] ?? "");
  const out: StreamedEdition[] = work.editions.map((edition) => ({
    slug: edition.slug,
    segments,
    versionTitle: edition.version,
    versionTitleHebrew: "",
    language: edition.language,
    license: edition.license,
    sourceUrl,
    pinned: true,
    error: segments.length ? undefined : error ?? "The archive returned no text for this chapter",
  }));
  const aligned = segments.length === expected;
  return {
    provider: "sacred-texts-json",
    upstream: work.upstream,
    upstreamRef: section.label || chapter.label,
    upstreamUrl: sourceUrl,
    fetchedAt: new Date().toISOString(),
    editions: out,
    aligned,
    cached: fromCache,
    notice: fromCache
      ? "The Internet Sacred Text Archive could not be read from this network, so the chapter is shown from the " +
        "transcription validated at import time and held in the library's own cache. Jacobi's translation is public domain."
      : aligned
        ? ""
        : `The archive now serves ${segments.length} paragraph(s) for this chapter where the library indexed ${expected}. The text is shown as received.`,
  };
}

// ---------------------------------------------------------------------------
// Heritage Scripture Server — IIT Kanpur, the Gita Supersite continued
// ---------------------------------------------------------------------------
//
// The corpus of the Gita Supersite is served from a documented REST API whose
// content routes answer an API key. This library holds each work's outline — its
// chapters and the address of every verse — and nothing else: the licence forbids
// bulk harvesting and the server meters by the verse, so the text is read one
// verse at a time, as a chapter is opened, cached in memory, and shown with the
// attribution HCAL-1.1 requires. The server's own `_meta` block, which names
// the licence and carries the watermark, is reproduced as it arrives.

type HeritageConfig = {
  api?: string;
  text: string;
  workUrl?: string;
  attribution?: string;
  /** Verses read per chapter request; defaults to CHAPTER_VERSE_LIMIT. */
  chapterVerseLimit?: number;
  /** Each chapter, with the addresses of the verses the server publishes for it. */
  chapters: Record<string, { label: string; verses: string[] }>;
};

const HERITAGE_API = "https://heritage.iitk.ac.in/api/v1";
const HERITAGE_SITE = "https://heritage.iitk.ac.in";
const HERITAGE_ATTRIBUTION = "Accessed via Heritage Scripture Server (heritage.iitk.ac.in), licence HCAL-1.1.";

// A verse costs one unit of the key's daily allowance, so a verse once received
// is kept for the life of the process rather than fetched again after the
// chapter cache expires. Nothing is written to disk, and the cache is bounded.
const verseCache = new Map<string, { at: number; text: string }>();
const VERSE_TTL = 6 * 60 * 60_000;
const VERSE_CACHE_LIMIT = 4_000;
// The largest chapter here is the Mahābhārata's Śānti Parva, at 12,866 verses,
// and every verse costs a unit of the key's allowance: one reader page cannot
// read a parva. A reader page reads the opening of a chapter; the notice says how
// much of it is shown and where the rest is read.
const CHAPTER_VERSE_LIMIT = 120;
const VERSE_CONCURRENCY = 3;
// The response shape of a moolam verse is not published in the API's schema, so
// the first empty 200 is reported once, with the keys the server sent, rather
// than leaving a chapter of blanks without a trail.
let heritageShapeReported = false;

function rememberVerse(key: string, text: string) {
  if (verseCache.size >= VERSE_CACHE_LIMIT) {
    const oldest = [...verseCache.entries()].sort((a, b) => a[1].at - b[1].at)[0];
    if (oldest) verseCache.delete(oldest[0]);
  }
  verseCache.set(key, { at: Date.now(), text });
}

function heritageVerseUrl(api: string, text: string, reference: string): string {
  return `${api}/${text}/${reference.replaceAll(".", "/")}/moolam/`;
}

/**
 * The Sanskrit text of one verse, wherever in the response the server puts it.
 * The reply carries the verse beside its own metadata, and the field it is named
 * by is the server's; this reads the first of the names it uses that holds text.
 */
export function heritageVerseText(body: unknown): string {
  if (typeof body === "string") return body.trim();
  if (!body || typeof body !== "object") return "";
  const record = body as Record<string, unknown>;
  for (const key of ["moolam", "text", "verse_text", "verseText", "content", "sanskrit", "sloka"]) {
    const value = record[key];
    if (typeof value === "string" && value.trim()) return value.trim();
    if (value && typeof value === "object") {
      const nested = heritageVerseText(value);
      if (nested) return nested;
    }
  }
  if (record.data) return heritageVerseText(record.data);
  return "";
}

/** The licence identifier and watermark the server returns with a verse. */
export function heritageMeta(body: unknown): { licence: string; watermark: string } {
  const record = (body && typeof body === "object" ? body : {}) as Record<string, unknown>;
  const meta = (record._meta && typeof record._meta === "object" ? record._meta : {}) as Record<string, unknown>;
  const licence = typeof meta.license === "string" ? meta.license : meta.licence;
  return {
    licence: typeof licence === "string" && licence ? licence : "HCAL-1.1",
    watermark: typeof meta.watermark === "string" ? meta.watermark : "",
  };
}

/**
 * Places the verses the server served against the addresses the chapter holds.
 * A verse that was not served leaves an empty slot rather than closing the gap,
 * so every verse keeps the reference of its own address.
 */
export function placeHeritageVerses(verses: string[], served: string[]): string[] {
  return verses.map((_, index) => served[index] ?? "");
}

/**
 * The chapter as the reader receives it. The verses are placed by their address:
 * `served[i]` is the text of `section.verses[i]`, and a verse that was not served
 * leaves an empty slot rather than closing the gap — closing it would move every
 * verse after it onto the reference of the one before.
 */
function heritageChapter(
  work: StreamWork,
  section: { label: string; verses: string[] },
  served: string[],
  expected: number,
  state: {
    notice: string;
    error?: string;
    shortfall?: string;
    licence?: string;
    watermark?: string;
    servedVerses?: number;
  },
): StreamedChapter {
  const config = work.config as HeritageConfig;
  const api = config.api ?? HERITAGE_API;
  const segments = placeHeritageVerses(section.verses, served);
  const held = segments.filter(Boolean).length;
  const aligned = segments.length === expected && held === segments.length;
  const mismatch =
    segments.length === expected
      ? ""
      : `The library indexes ${expected} verse(s) for this chapter and the server publishes ${segments.length}.`;
  return {
    provider: "heritage",
    upstream: work.upstream,
    upstreamRef: section.label,
    upstreamUrl: config.workUrl ?? HERITAGE_SITE,
    fetchedAt: new Date().toISOString(),
    editions: work.editions.map((edition) => ({
      slug: edition.slug,
      segments,
      versionTitle: edition.version,
      versionTitleHebrew: "",
      language: edition.language,
      license: edition.license,
      sourceUrl: section.verses[0]
        ? heritageVerseUrl(api, config.text, section.verses[0])
        : (config.workUrl ?? HERITAGE_SITE),
      pinned: true,
      error: state.error,
    })),
    aligned,
    cached: false,
    servedVerses: state.servedVerses,
    notice: [
      state.notice,
      // The attribution already names HCAL-1.1, so the server's own licence line
      // is only added when it says something the attribution does not.
      state.licence && !state.notice.includes(state.licence) ? `Licence ${state.licence}.` : "",
      state.watermark,
      state.shortfall,
      mismatch,
      aligned ? "Shown as received, for non-commercial reading." : "",
    ]
      .filter(Boolean)
      .join(" "),
  };
}

async function fetchHeritage(
  work: StreamWork,
  chapter: { ref: string; label: string },
  expected: number,
): Promise<StreamedChapter | null> {
  const config = work.config as HeritageConfig;
  const section = config.chapters?.[chapter.ref];
  if (!section) return null;
  const api = config.api ?? HERITAGE_API;
  const attribution = config.attribution ?? HERITAGE_ATTRIBUTION;
  const configured = Number(config.chapterVerseLimit);
  const limit = Number.isFinite(configured) && configured > 0 ? Math.floor(configured) : CHAPTER_VERSE_LIMIT;
  const addresses = section.verses.slice(0, limit);
  const truncated = section.verses.length > addresses.length;
  const key = (process.env.HERITAGE_API_KEY ?? "").trim();
  if (!key) {
    // The outline is held and the verses are not: they are served only to a key
    // Heritage issues on request. The chapter says what it is, who serves it and
    // where the key comes from, rather than showing an unexplained empty page.
    // It is bounded by the same verse limit either way: a parva is not a page.
    return heritageChapter(work, section, [], expected, {
      notice:
        `${attribution} The verses are served to an API key that Heritage IITKanpur issues on request — ` +
        `write to heritage.iitk@gmail.com, or use the request form that ${api}/request-access/ accepts. ` +
        `This library holds the outline and streams the text; set HERITAGE_API_KEY to read it.`,
      servedVerses: addresses.length,
    });
  }
  // Addressed by verse, not by arrival: three verses arrive concurrently and one
  // may fail, and neither may move the text onto another verse's reference.
  const served: string[] = new Array(addresses.length).fill("");
  let error: string | undefined;
  let licence = "";
  let watermark = "";
  let next = 0;
  const readOne = async (): Promise<void> => {
    while (!error) {
      const index = next++;
      if (index >= addresses.length) return;
      const reference = addresses[index];
      const cacheKey = `${work.slug}:${reference}`;
      const hit = verseCache.get(cacheKey);
      if (hit && Date.now() - hit.at < VERSE_TTL) {
        served[index] = hit.text;
        continue;
      }
      let status = 0;
      let body: unknown;
      try {
        ({ status, body } = await fetchJson(heritageVerseUrl(api, config.text, reference), {
          headers: { authorization: `Api-Key ${key}` },
          timeoutMs: 20_000,
          // A spent allowance answers 429 until it resets, so a retry only
          // spends three requests to learn what the first already said. The same
          // holds for a 5xx, which is how this server refuses a key it does not
          // recognise rather than reporting a fault of its own.
          retryOn429: false,
          retryOn5xx: false,
        }));
      } catch (err) {
        error = (err as Error).message;
        return;
      }
      if (status === 401 || status === 403) {
        error = "the key was refused";
        return;
      }
      if (status === 429) {
        error = "the key's allowance for the day is spent";
        return;
      }
      if (status >= 500) {
        // The server answers 500, not 403, to a key it does not recognise.
        error = `the server answered ${status}, which is how it answers a key it does not accept`;
        return;
      }
      if (status !== 200) {
        error = `the server answered ${status}`;
        return;
      }
      const text = heritageVerseText(body);
      if (!text && !heritageShapeReported && body && typeof body === "object") {
        heritageShapeReported = true;
        console.warn(
          `Heritage answered 200 for ${reference} with no verse text; response keys: ${Object.keys(body as Record<string, unknown>).join(", ")}`,
        );
      }
      served[index] = text;
      if (text) rememberVerse(cacheKey, text);
      const meta = heritageMeta(body);
      licence = licence || meta.licence;
      watermark = watermark || meta.watermark;
    }
  };
  await Promise.all(Array.from({ length: Math.min(VERSE_CONCURRENCY, addresses.length) }, readOne));
  // A verse can come back empty without anything failing, and an empty slot the
  // reader cannot explain is worse than no slot: say how many of the verses read
  // carried no text. Only the verses this read attempted are counted, so a
  // chapter shortened to its verse limit is not reported as a loss.
  const held = served.filter(Boolean).length;
  const shortfall = error
    ? `${held} of ${addresses.length} verse(s) arrived (${error}).`
    : held < addresses.length
      ? `${addresses.length - held} of ${addresses.length} verse(s) came back empty from the server.`
      : "";
  const notice = truncated
    ? `${attribution} This chapter holds ${section.verses.length} verses; the first ${addresses.length} are read here, because the server serves them a verse at a time against a metered key. The rest are read at ${config.workUrl ?? HERITAGE_SITE}.`
    : attribution;
  return heritageChapter(work, section, served, expected, {
    notice,
    error,
    shortfall,
    licence,
    watermark,
    servedVerses: addresses.length,
  });
}

