function sefariaRef(work: StreamWork, chapter: { ref: string; label: string }, form: "numbered" | "complex"): string {
  if (form === "complex") {
    return `${work.upstream},_${String(chapter.label).replaceAll(" ", "_")}`;
  }
  return `${work.upstream}.${chapter.ref}`;
}

async function sefariaEdition(
  work: StreamWork,
  chapter: { ref: string; label: string },
  edition: StreamEditionConfig,
  form: "numbered" | "complex",
  expected: number,
): Promise<StreamedEdition> {
  const ref = sefariaRef(work, chapter, form);
  const url = new URL(`https://www.sefaria.org/api/v3/texts/${encodeURIComponent(ref)}`);
  url.searchParams.set("version", `${edition.languageName}|${edition.version}`);
  let body: any = null;
  let status = 0;
  try {
    const result = await fetchJson(url.toString());
    body = result.body;
    status = result.status;
  } catch (err) {
    return {
      slug: edition.slug,
      segments: [],
      versionTitle: edition.version,
      versionTitleHebrew: "",
      language: edition.language,
      license: edition.license,
      sourceUrl: edition.sourceUrl,
      pinned: true,
      error: (err as Error).message,
    };
  }
  const version = body?.versions?.[0];
  if (status !== 200 || !version) {
    return {
      slug: edition.slug,
      segments: [],
      versionTitle: edition.version,
      versionTitleHebrew: "",
      language: edition.language,
      license: edition.license,
      sourceUrl: edition.sourceUrl,
      pinned: true,
      error: body?.error ? String(body.error) : `Sefaria returned no ${edition.version} text`,
    };
  }
  const title = String(version.versionTitle ?? edition.version);
  return {
    slug: edition.slug,
    segments: segmentsFor(version.text, expected),
    versionTitle: title,
    versionTitleHebrew: String(version.versionTitleInHebrew ?? ""),
    language: String(version.language ?? edition.language),
    license: String(version.license ?? edition.license ?? ""),
    sourceUrl: String(version.versionSource ?? ""),
    pinned: title === edition.version,
  };
}

async function fetchSefaria(
  work: StreamWork,
  chapter: { ref: string; label: string },
  expected: number,
): Promise<StreamedChapter | null> {
  const forms: ("numbered" | "complex")[] =
    work.mode === "complex" ? ["complex", "numbered"] : ["numbered", "complex"];
  let best: { form: "numbered" | "complex"; editions: StreamedEdition[]; score: number } | null = null;
  for (const form of forms) {
    const editions = await Promise.all(work.editions.map((e) => sefariaEdition(work, chapter, e, form, expected)));
    const usable = editions.filter((e) => e.segments.length > 0);
    if (!usable.length) continue;
    const aligned = usable.some((e) => e.segments.length === expected);
    if (aligned) {
      return finalise(work, chapter, form, editions, true);
    }
    const closest = usable.reduce((a, b) => (Math.abs(b.segments.length - expected) < Math.abs(a.segments.length - expected) ? b : a));
    const score = Math.abs(closest.segments.length - expected);
    if (!best || score < best.score) best = { form, editions, score };
  }
  if (!best) return null;
  return finalise(work, chapter, best.form, best.editions, false);
}

function finalise(
  work: StreamWork,
  chapter: { ref: string; label: string },
  form: string,
  editions: StreamedEdition[],
  aligned: boolean,
): StreamedChapter {
  const apiRef = form === "complex" ? `${work.upstream}, ${chapter.label}` : `${work.upstream} ${chapter.ref}`;
  const url = `https://www.sefaria.org/${encodeURIComponent(apiRef.replaceAll(" ", "_"))}`;
  return {
    provider: work.provider,
    upstream: work.upstream,
    upstreamRef: apiRef,
    upstreamUrl: url,
    fetchedAt: new Date().toISOString(),
    editions,
    aligned,
    cached: false,
    notice: aligned
      ? ""
      : `The hosted source divides this chapter differently from the library's index (${editions
          .map((e) => `${e.segments.length}`)
          .join(" / ")} segments). The upstream text is shown as received.`,
  };
}

