/**
 * Continuous chapter reading.
 *
 * The passage cards and their controls are for study: each verse or article
 * stands alone with its own links. This view removes that scaffolding so a
 * chapter can be read straight through. Poetry and other line-by-line texts are
 * joined into one column instead of a paragraph per line, and passage marks are
 * hidden unless the reader turns them on.
 */
function ContinuousChapter({
  slug,
  passages,
  view,
  scheme,
  showRefs,
}: {
  slug: string;
  passages: any[];
  view: TextView;
  scheme: string;
  showRefs: boolean;
}) {
  const runIn = scheme === "chapter.paragraph" || scheme === "chapter.article" || scheme === "chapter.section";
  const parallelOriginal = passages.find((p: any) => p.original)?.original;
  const parallelTranslation = passages.find((p: any) => p.translation)?.translation;
  const panes: {
    key: string;
    kicker: string;
    language: string;
    edition: string;
    source: string;
    lang?: string;
    rtl: boolean;
    items: { reference: string; label: string; text: string }[];
  }[] = [];

  if (parallelOriginal || parallelTranslation) {
    if (view !== "english" && parallelOriginal) {
      panes.push({
        key: "original",
        kicker: "Original text",
        language: parallelOriginal.language?.name ?? "",
        edition: parallelOriginal.title ?? "",
        source: parallelOriginal.source?.name ?? "",
        lang: parallelOriginal.language?.code,
        rtl: parallelOriginal.language?.direction === "rtl",
        items: passages
          .filter((p: any) => p.original)
          .map((p: any) => ({ reference: p.reference, label: p.label, text: p.original.text })),
      });
    }
    if (view !== "original" && parallelTranslation) {
      panes.push({
        key: "translation",
        kicker: "Translation",
        language: parallelTranslation.language?.name ?? "",
        edition: parallelTranslation.title ?? "",
        source: parallelTranslation.source?.name ?? "",
        lang: parallelTranslation.language?.code,
        rtl: parallelTranslation.language?.direction === "rtl",
        items: passages
          .filter((p: any) => p.translation)
          .map((p: any) => ({ reference: p.reference, label: p.label, text: p.translation.text })),
      });
    }
  } else {
    const edition = passages.find((p: any) => p.edition)?.edition;
    panes.push({
      key: "single",
      kicker: edition?.editionType === "original" ? "Original text" : "Text",
      language: edition?.language?.name ?? "",
      edition: edition?.title ?? "",
      source: edition?.source?.name ?? "",
      lang: edition?.language?.code,
      rtl: edition?.language?.direction === "rtl",
      items: passages
        .filter((p: any) => p.text)
        .map((p: any) => ({ reference: p.reference, label: p.label, text: p.text })),
    });
  }

  const visible = panes.filter((pane) => pane.items.length > 0);
  if (!visible.length) return <p className="muted">The hosted text returned no readable segments for this chapter.</p>;

  return (
    <div className="chapter-flow-wrap">
      {visible.map((pane) => {
        const lineated = looksLineated(pane.items, scheme);
        return (
          <section key={pane.key} className="chapter-flow">
            <header className="flow-head">
              <span className="flow-kicker">{pane.kicker}</span>
              {pane.language && <span className="flow-language">{pane.language}</span>}
              {pane.edition && (
                <span className="flow-edition">
                  {pane.edition}
                  {pane.source ? ` · via ${pane.source}` : ""}
                </span>
              )}
            </header>
            <div className={pane.rtl ? "flow-text rtl" : "flow-text"} dir={pane.rtl ? "rtl" : "ltr"} lang={pane.lang}>
              {lineated ? (
                <p className="flow-para flow-verse">
                  {pane.items.map((item, index) => (
                    <Fragment key={item.reference}>
                      {showRefs && (
                        <a
                          className="flow-marker"
                          href={`/read/${slug}?ref=${encodeURIComponent(item.reference)}`}
                          title={`${item.label} — open this line on its own`}
                        >
                          {flowMarker(item)}
                        </a>
                      )}
                      {item.text.split(/\n{2,}/).map((chunk, i) => (
                        <Fragment key={i}>
                          {i > 0 && (
                            <>
                              <br />
                              <br />
                            </>
                          )}
                          {chunk}
                        </Fragment>
                      ))}
                      {index < pane.items.length - 1 && <br />}
                    </Fragment>
                  ))}
                </p>
              ) : (
                pane.items.map((item) => (
                  <p key={item.reference} className="flow-para">
                    {showRefs &&
                      (runIn ? (
                        <span className="flow-runin">{item.label}</span>
                      ) : (
                        <a
                          className="flow-marker"
                          href={`/read/${slug}?ref=${encodeURIComponent(item.reference)}`}
                          title={`${item.label} — open this passage on its own`}
                        >
                          {flowMarker(item)}
                        </a>
                      ))}
                    {item.text.split(/\n{2,}/).map((chunk, i) => (
                      <Fragment key={i}>
                        {i > 0 && (
                          <>
                            <br />
                            <br />
                          </>
                        )}
                        {chunk}
                      </Fragment>
                    ))}
                  </p>
                ))
              )}
            </div>
          </section>
        );
      })}
      <p className="flow-note">
        {showRefs
          ? "Read as one block. The small references mark the passage being quoted and open it on its own; nothing else interrupts the chapter."
          : "Read as one block, with passage marks hidden. Turn on references above to quote or open a single passage."}
      </p>
    </div>
  );
}

/**
 * Whether a chapter is set line by line (poetry, verse) rather than in
 * paragraphs. A paragraph gap after every verse would break the poem apart, so
 * these passages are joined into one column. The scheme check keeps prose
 * schemes such as ayahs and hadith on their own paragraphs: many of those are
 * short too, but they are not lines of one poem.
 */
function looksLineated(items: { text: string }[], scheme: string) {
  const lineish = scheme === "chapter.paragraph" || scheme === "chapter.verse" || scheme === "verse" || scheme.endsWith(".line");
  if (!lineish) return false;
  if (items.length < 8) return false;
  const short = items.filter((item) => item.text.trim().length <= 90).length;
  return short / items.length >= 0.7;
}

/**
 * Jump to another chapter without leaving the reader. Works with a single
 * chapter keep their header clean, and long works rely on the select's own
 * type-ahead rather than an extra search box.
 */
function ChapterPicker({
  slug,
  chapters,
  current,
  version,
}: {
  slug: string;
  chapters: { ref: string; label: string }[];
  current: string;
  version?: string | null;
}) {
  if (chapters.length < 2) return null;
  const index = chapters.findIndex((c) => c.ref === current);
  return (
    <div className="chapter-jump">
      <label>
        <span>Chapter</span>
        <select
          aria-label="Choose a chapter"
          value={index >= 0 ? current : chapters[0].ref}
          onChange={(e) =>
            navigate(
              `/read/${slug}?ref=${encodeURIComponent(e.target.value)}${version ? `&version=${encodeURIComponent(version)}` : ""}`,
            )
          }
        >
          {chapters.map((c) => (
            <option key={c.ref} value={c.ref}>
              {c.label}
            </option>
          ))}
        </select>
      </label>
      <span className="muted">{index >= 0 ? `${index + 1} of ${chapters.length}` : `${chapters.length} chapters`}</span>
    </div>
  );
}

/** The smallest reference that still identifies a passage in a continuous flow. */
function flowMarker(item: { reference: string; label: string }) {
  const ref = item.reference ?? "";
  const tail = ref.includes(":") ? ref.slice(ref.lastIndexOf(":") + 1) : ref.slice(ref.lastIndexOf(".") + 1);
  return tail || item.label;
}

function versionLabel(v: any) {
  const bits = [v.language?.name, v.editionType === "original" ? "original" : v.translator ? `trans. ${v.translator}` : "translation"];
  return `${bits.filter(Boolean).join(" · ")} — ${v.title}`;
}

